// Что открыто без подписки, а что за ней.
//
// Владелец: «спрячь все экраны кроме футбольного алиаса в подписку pro».
//
// ⚠️ СПИСОК ЗДЕСЬ — БЕЛЫЙ, А НЕ ЧЁРНЫЙ, И ЭТО РЕШЕНИЕ, А НЕ ПРИВЫЧКА. Чёрный
// список («вот это закрыто») протекает при КАЖДОМ новом экране: маршрут
// добавили, в список внести забыли — и платный экран тихо открыт всем. Белый
// ошибается в обратную сторону: забытый маршрут окажется закрыт, это заметят
// сразу и починят одной строкой. Из двух ошибок эта дешевле.
//
// ⚠️ `/pro` ОБЯЗАН БЫТЬ ОТКРЫТ, ИНАЧЕ ПЕТЛЯ. Не-Pro на закрытом маршруте
// отправляется на `/pro`; закрой и его — и он отправится сам на себя, навсегда.
// На это стоит отдельная проверка в тестах: она ловит ровно ту опечатку,
// которая превращает платёжный экран в недостижимый.
//
// ⚠️ ЭТО ВОРОТА ЭКРАНА, А НЕ ЗАЩИТА ДАННЫХ. Мини-приложение живёт на клиенте,
// и спрятанный маршрут не закрывает RPC: тот, кто откроет devtools, по-прежнему
// вызовет `club_news` или `player_index` напрямую — они анонимные по замыслу,
// на них держатся и бот, и превью. Настоящее ограничение доступа к данным
// потребовало бы проверки `is_pro` внутри каждой функции и переписывания RLS;
// здесь этого нет, и делать вид, что есть, нельзя.

/** Точные маршруты, открытые всем. */
const FREE_EXACT = new Set([
  '/',          // главная
  '/lobby',     // сбор команд
  '/game',      // сам алиас
  '/end',       // итоги раунда
  '/training',  // тот же алиас в одиночку
  '/tutorial',  // как играть
  '/profile',   // свой профиль: отсюда управляют подпиской
  '/pro',       // сама подписка — см. про петлю выше
  '/admin',     // редактор карточек, в меню не показан и к подписке не относится
]);

/**
 * Нужна ли подписка, чтобы открыть этот маршрут.
 *
 * Сравнение идёт по пути БЕЗ строки запроса: `/collection?view=stats` — это
 * тот же экран коллекции, и открывать его через `?view=` было бы дырой
 * размером со все рейтинги.
 */
export function requiresPro(pathname: string): boolean {
  const path = (pathname || '/').split('?')[0].split('#')[0];
  // Хвостовой слэш — тот же экран: `/news/` не должен обходить ворота.
  const clean = path.length > 1 && path.endsWith('/') ? path.slice(0, -1) : path;
  return !FREE_EXACT.has(clean);
}

/** Маршруты, открытые всем, — для проверок и для подписи в интерфейсе. */
export const FREE_ROUTES: readonly string[] = [...FREE_EXACT];
