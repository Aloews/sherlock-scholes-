import type { NavigateFunction } from 'react-router-dom';

/**
 * «Назад» — ТУДА, ОТКУДА ПРИШЛИ, а не всегда на главную.
 *
 * Владелец: «добавь кнопку назад в вне игровых экранах для навигации, и создай
 * систему навигации, так как приложение очень большое».
 *
 * ⚠️ ЗАМЕР, А НЕ ВПЕЧАТЛЕНИЕ: из 14 экранов с кнопкой «назад» ДЕВЯТЬ вели
 * жёстко на главную и только четыре — по истории. То есть открыв клуб из
 * рейтинга, из матчей или из коллекции, читатель одинаково оказывался на
 * главной и терял место, к которому шёл. При двадцати трёх экранах это и
 * есть «приложение очень большое».
 *
 * ⚠️ ЗАПАСНОЙ ПУТЬ ОБЯЗАТЕЛЕН. `navigate(-1)` при пустой истории не делает
 * НИЧЕГО, и кнопка выглядит сломанной. Пустая история — не редкость: карточку
 * открывают по прямой ссылке из Telegram, и она первая в стопке. Поэтому
 * запасной путь — главная, а не молчание.
 */
export function goBack(navigate: NavigateFunction, fallback = '/'): void {
  if (typeof window !== 'undefined' && window.history.length > 1) {
    navigate(-1);
    return;
  }
  navigate(fallback);
}
