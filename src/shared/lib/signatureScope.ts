/**
 * Куда едет подпись Telegram, а куда НЕТ.
 *
 * ⚠️ ОТДЕЛЬНЫМ ФАЙЛОМ НАРОЧНО. `supabase.ts` бросает при загрузке, если нет
 * VITE_SUPABASE_*, — и правило, спрятанное внутри него, нельзя проверить
 * тестом, не подсовывая окружение. Правило важнее удобства: здесь оно голое,
 * без побочных действий, и проверяется напрямую.
 *
 * ⚠️ ПОДПИСЬ НУЖНА ТОЛЬКО PostgREST, И ОТПРАВЛЯТЬ ЕЁ КУДА-ТО ЕЩЁ ОКАЗАЛОСЬ НЕ
 * ПРОСТО ЛИШНИМ, А ПОЛОМКОЙ. `require_pro()` живёт в базе и читает
 * `request.headers ->> 'x-tg-init-data'`; Edge-функции получают initData телом
 * запроса и заголовок не смотрят вовсе.
 *
 * Пока заголовок ставился на ВСЁ, его получал и `functions.invoke`. На
 * нестандартный заголовок браузер шлёт предзапрос OPTIONS, а список
 * разрешённых у Edge-функций прибит гвоздями — `x-tg-init-data` в нём не было,
 * и браузер блокировал вызов ЦЕЛИКОМ, ещё до отправки. Владелец: «сводка
 * новостей по кнопке „собрать сводку“ не работает». Вместе со сводкой молча
 * перестали работать вход в комнату, ОПЛАТА Pro и загрузка логотипа.
 *
 * ⚠️ СЕРВЕР ПРИ ЭТОМ БЫЛ ЖИВ: прямой POST тем же ключом отвечал 200 за 2.6 с.
 * Предзапрос делает браузер, поэтому ни curl, ни `check-prod` этого не видели.
 *
 * ⚠️ И ЭТО НЕ ТОЛЬКО ПРО ПОЧИНКУ. initData — подписанный пропуск игрока.
 * Отправлять его туда, где он не нужен, незачем: заголовок уезжал в каждую
 * функцию, включая те, что ходят к чужим службам.
 */
export function needsSignature(url: string): boolean {
  return url.includes('/rest/v1/') || url.includes('/realtime/v1/');
}
