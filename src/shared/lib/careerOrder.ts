/**
 * Порядок клубной карьеры: ОТ ПОСЛЕДНЕГО КЛУБА К ПЕРВОМУ.
 *
 * Владелец: «сортировку клубной карьеры нужно изменить, не по количеству
 * проведенных матчей, а по годам, от последнего клуба к первому».
 *
 * ⚠️ ПОРЯДОК ПРИХОДИЛ ИЗ БАЗЫ И ЗНАЧИЛ РАЗНОЕ У РАЗНЫХ КАРТОЧЕК. `career_stats`
 * собирается по числу матчей, `legend_career` — как перечислено в статье. То
 * есть на одном экране рядом стояли две разные сортировки, и ни одна не
 * отвечала на вопрос «где он играет сейчас», ради которого карьеру и смотрят.
 *
 * ⚠️ ГОДЫ — СТРОКА, И РАЗНАЯ. В базе лежат «2018–2021», «2021–2021», «2022–»,
 * «2022-2023» и просто «2019». Разделитель бывает и коротким дефисом, и
 * длинным тире; открытый конец значит «играет сейчас». Поэтому разбор — по
 * ЧИСЛАМ в строке, а не по формату: формат меняется, четырёхзначные годы нет.
 *
 * ⚠️ ОТКРЫТЫЙ КОНЕЦ — САМЫЙ СВЕЖИЙ, и это не мелочь: именно текущий клуб
 * владелец и ждёт сверху. «2022–» обязан обойти «2021–2023», хотя начался
 * раньше конца соперника.
 */

/** Границы периода. `end === null` — «по сей день». */
export interface CareerYears {
  start: number | null;
  end: number | null;
}

/** Год «сейчас» для открытого периода — больше любого реального года. */
const OPEN_END = 9999;

/**
 * Годы из строки. ЧИСТАЯ ФУНКЦИЯ — её проверяет тест.
 *
 * Берутся все четырёхзначные числа: первое — начало, второе — конец. Если
 * второго нет, но в строке есть разделитель, конец открыт.
 */
export function parseYears(years: string | null | undefined): CareerYears {
  const text = (years ?? '').trim();
  const found = text.match(/\d{4}/g);
  if (!found || found.length === 0) return { start: null, end: null };
  const start = Number(found[0]);
  if (found.length > 1) return { start, end: Number(found[1]) };
  // Один год: «2022–» — играет сейчас, «2019» — один сезон.
  const openEnded = /\d{4}\s*[-–—]\s*$/.test(text);
  return { start, end: openEnded ? null : start };
}

/**
 * Сравнение двух строк карьеры: свежая раньше старой.
 *
 * Сначала по концу (кто ушёл позже — тот выше), потом по началу. Обратный
 * порядок дал бы «2022–2023» выше «2020–2026»: начался позже, а закончился
 * раньше.
 */
export function compareCareer(a: string | null | undefined, b: string | null | undefined): number {
  const x = parseYears(a);
  const y = parseYears(b);
  // Строка без годов уходит вниз: гадать за неё нечем, а наверху она заняла бы
  // место текущего клуба.
  if (x.start === null && y.start === null) return 0;
  if (x.start === null) return 1;
  if (y.start === null) return -1;
  const endX = x.end === null ? OPEN_END : x.end;
  const endY = y.end === null ? OPEN_END : y.end;
  if (endX !== endY) return endY - endX;
  return (y.start ?? 0) - (x.start ?? 0);
}

/**
 * Карьера в порядке показа. Копия, а не сортировка на месте: массив приходит
 * из состояния React, и менять его молча нельзя.
 */
export function byLatestFirst<T extends { meta: string }>(rows: readonly T[]): T[] {
  return [...rows].sort((a, b) => compareCareer(a.meta, b.meta));
}
