// Позиция Soccer Wiki: код источника → линия и стороны поля.
//
// КАК ВЫГЛЯДИТ КОД, ЗАМЕРЕНО НА 1000 ЖИВЫХ СТРОК 07.09.2026:
//
//     Gk | D(C) | D,DM,M(L) | DM,M(C) | M,AM(C) | AM(RL),F(RLC) | F(C)
//
// Группы позиций через запятую, стороны в скобках у КОНЦА группы: `AM(RL)` —
// атакующий полузащитник справа и слева. Встречающиеся коды и только они:
// Gk, D, DM, M, AM, F; стороны R, L, C и их сочетания.
//
// ⚠️ ЛИНИЯ БЕРЁТСЯ ПО ПЕРВОМУ КОДУ, А НЕ ПО ПОСЛЕДНЕМУ И НЕ ПО «САМОМУ
// АТАКУЮЩЕМУ». Источник перечисляет позиции от самой глубокой к самой
// передней, и первая — основная: у Райса `DM,M(C)` основная DM, у Саки
// `M,AM(R)` — полузащита. Взяв последнюю, состав получил бы Райса в
// полузащите атаки, а половину защитников — в центре поля.
//
// ⚠️ НЕИЗВЕСТНЫЙ КОД ДАЁТ null, А НЕ «ПОЛУЗАЩИТНИК». Разметка источника
// поменяется — состав встанет одним списком без линий, и это будет видно. Тихая
// подстановка средней линии выглядела бы как настоящий состав.

export type SwLine = 'gk' | 'def' | 'mid' | 'fwd';

/** Порядок линий на экране состава: от ворот к чужим воротам. */
export const SW_LINES: SwLine[] = ['gk', 'def', 'mid', 'fwd'];

const LINE_BY_CODE: Record<string, SwLine> = {
  gk: 'gk',
  d:  'def',
  dm: 'mid',
  m:  'mid',
  am: 'mid',
  f:  'fwd',
};

/** Линия игрока или null, если код не разобрался. ЧИСТАЯ ФУНКЦИЯ. */
export function swLine(position: string | null | undefined): SwLine | null {
  const first = (position ?? '').trim().split(',')[0] ?? '';
  const code = first.replace(/\(.*$/, '').trim().toLowerCase();
  return LINE_BY_CODE[code] ?? null;
}

/** Стороны поля первой группы: 'RLC' → 'RLC'. Пусто, если сторон нет. */
export function swSides(position: string | null | undefined): string {
  const m = /\(([RLC]+)\)/i.exec((position ?? '').trim().split(',')[0] ?? '');
  return m ? m[1].toUpperCase() : '';
}

// Рейтинг источника раскрашивается ТОЙ ЖЕ ЛЕСТНИЦЕЙ, что и редкость карточки,
// чтобы 94 и 68 отличались на экране с одного взгляда. Границы взяты по
// живому распределению: 90+ — верхушка мирового футбола, 80+ — основа топ-лиг.
//
// ⚠️ ЭТО ЦВЕТ, А НЕ ЗНАЧЕНИЕ. Редкость карточки считает `fame_tier()` по
// просмотрам Википедии, и совпадение шкал случайно: известность и оценка
// читателей — разные величины. Здесь берётся только палитра.
export function swRatingTier(rating: number | null | undefined):
  'icon' | 'legendary' | 'epic' | 'rare' | 'common' {
  if (rating == null) return 'common';
  if (rating >= 92) return 'icon';
  if (rating >= 85) return 'legendary';
  if (rating >= 78) return 'epic';
  if (rating >= 70) return 'rare';
  return 'common';
}
