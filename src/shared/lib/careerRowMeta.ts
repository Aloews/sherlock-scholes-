/**
 * Правая колонка строки клубной карьеры: ДОСТИЖЕНИЕ, а не годы.
 *
 * Владелец: «года в карточке так и не поменял, на лучшие достижения игрока, в
 * годах можно указать дату рождения».
 *
 * ⚠️ ЧТО БЫЛО НЕ ТАК. Строка карьеры выглядела как «Барселона · 2004–2021»:
 * справа стояли годы — то есть КОГДА, а не ЧТО. Человек открывает карьеру,
 * чтобы узнать, чего игрок добился, и получает диапазон дат. Матчи и голы за
 * тот же клуб лежали в той же самой строке `career_stats` и не показывались
 * вовсе.
 *
 * ⚠️ ГОДЫ НЕ ВЫБРОШЕНЫ, А ОТОДВИНУТЫ. У легенды (`legend_career.clubs`) чисел
 * нет вообще — там годы это всё, что известно, и заменить их нечем. Поэтому
 * лестница: числа, если они есть; годы, если чисел нет; пусто, если нет ни
 * того ни другого. Пустая строка честнее выдуманной.
 *
 * ⚠️ НОЛЬ МАТЧЕЙ — ЭТО НЕ ДОСТИЖЕНИЕ, А ОТСУТСТВИЕ ДАННЫХ. В инфобоксе
 * Википедии у клуба, за который игрок не сыграл ни разу, стоит «0», и у клуба,
 * про который она не знает, — тоже. Показать «0 матчей» значит утверждать
 * первое, имея второе, поэтому ноль откатывается на годы.
 */
export interface CareerRowSource {
  years?: string | null;
  apps?: number | null;
  goals?: number | null;
}

export interface CareerRowMeta {
  /** 'numbers' — матчи и голы; 'years' — диапазон лет; null — показывать нечего. */
  kind: 'numbers' | 'years' | null;
  apps: number;
  goals: number;
  years: string;
}

export function careerRowMeta(row: CareerRowSource): CareerRowMeta {
  const apps = row.apps ?? 0;
  const goals = row.goals ?? 0;
  const years = (row.years ?? '').trim();
  if (apps > 0) return { kind: 'numbers', apps, goals, years };
  if (years) return { kind: 'years', apps, goals, years };
  return { kind: null, apps, goals, years };
}
