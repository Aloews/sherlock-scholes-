// Комната сетевой арены, пережившая перезапуск приложения.
//
// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Код комнаты жил только в состоянии компонента, а
// мини-приложение Telegram перезапускается штатно — это записано в §9 карты
// («свёрнутое мини-приложение — ЖИВОЙ документ», и наоборот, закрытое
// поднимается заново). После перезапуска игрок оказывался на экране ввода
// кода, посреди матча.
//
// ⚠️ И ХУЖЕ ВСЕГО ЭТО БЫЛО ХОСТУ. Его код сгенерирован случайно (`newCode`) и
// нигде не показан до входа в комнату: гость свой код хотя бы НАБИРАЛ руками и
// мог вспомнить, а хост — нет. Для него перезапуск означал не «переподключись»,
// а «комната потеряна навсегда, соперник ждёт в комнате, куда никто не придёт».
//
// ПОЧЕМУ localStorage, А НЕ CloudStorage. CloudStorage синхронизируется
// Telegram между УСТРОЙСТВАМИ пользователя, а комната привязана к устройству:
// хост считает физику здесь. Подтянуть код на планшет, где игры нет, значит
// предложить вернуться в комнату, из которой сюда никто не подключался.
// К тому же CloudStorage асинхронен, а решение «показать поле или экран ввода»
// принимается первым же рендером.
//
// ПОЧЕМУ НЕ sessionStorage. Он и есть то, что перезапуск НЕ переживает: новый
// запуск мини-приложения — новая сессия. Ровно тот случай, ради которого всё
// это написано.
//
// ⚠️ ВОЗВРАЩАЕТСЯ КОМНАТА, А НЕ СЧЁТ, и путать это нельзя. Физику считает хост,
// в памяти своего телефона: его перезапуск начинает матч заново с 0:0, и гость
// увидит это первым же снимком. Перезапуск ГОСТЯ счёт переживает — счёт
// приходит от хоста, который никуда не девался.
//
// Хранить счёт здесь было бы хуже, чем не хранить: две стороны записывали бы
// его независимо, и после перезапуска обоих они разошлись бы — а разошедшийся
// счёт уходит в `record_arena_result`, где матч засчитывается только при
// зеркальном совпадении половин. То есть попытка сохранить счёт превратила бы
// «матч начался заново» в «матч не засчитан вовсе».

import { normalizeCode } from '@/features/lobby/invite';
import type { NetRole } from './useArenaNet';

const KEY = 'arena.room';

/**
 * Сколько живёт запомненная комната.
 *
 * Пятнадцать минут — не про длину матча (он идёт минуты), а про длину
 * ПЕРЕРЫВА, который игрок считает продолжением той же игры: входящий звонок,
 * ушедший в карман телефон, метро. Больше — и вчерашний код воскресал бы в
 * комнате, где давно никого нет; меньше — и отлучка за дверь стоила бы матча.
 *
 * Верхняя граница здесь безопасна в обе стороны: комната — это просто имя
 * канала, и вход в мёртвую даёт «ждём соперника», а не поломку.
 */
export const ROOM_TTL_MS = 15 * 60 * 1000;

export interface ArenaRoom {
  code: string;
  role: NetRole;
}

interface Stored extends ArenaRoom {
  /** Когда записали, по местным часам. */
  at: number;
}

/**
 * Чтение с проверкой, а не приведением типов.
 *
 * ⚠️ ЭТО НЕДОВЕРЕННЫЙ ВВОД, хотя писали его мы сами. В localStorage лезут
 * расширения, его переживает выкатка новой версии с другим форматом, и он
 * доступен любому скрипту на странице. Строка «h» вместо роли отправила бы
 * гостя считать физику; код с посторонними символами ушёл бы в имя канала.
 * Поэтому обе половины проверяются теми же правилами, что и ввод с экрана:
 * код — через `normalizeCode` (единственное место, где живёт форма кода), роль
 * — точным сравнением с двумя допустимыми значениями.
 */
export function readRoom(now: number = Date.now()): ArenaRoom | null {
  let raw: string | null = null;
  try {
    raw = localStorage.getItem(KEY);
  } catch {
    // Приватный режим и часть WebView бросают на самом доступе. Отсутствие
    // хранилища — это «нечего восстанавливать», а не ошибка экрана.
    return null;
  }
  if (!raw) return null;

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (!parsed || typeof parsed !== 'object') return null;

  const s = parsed as Partial<Stored>;
  const code = normalizeCode(typeof s.code === 'string' ? s.code : null);
  if (!code) return null;
  if (s.role !== 'host' && s.role !== 'guest') return null;
  if (typeof s.at !== 'number' || !Number.isFinite(s.at)) return null;

  // Часы могли уехать назад (перевод времени, синхронизация NTP), и тогда
  // возраст выходит отрицательным. Такая запись не «из будущего» в смысле
  // подделки — она просто не поддаётся оценке, и брать её нельзя.
  const age = now - s.at;
  if (age < 0 || age > ROOM_TTL_MS) return null;

  return { code, role: s.role };
}

export function writeRoom(room: ArenaRoom, now: number = Date.now()): void {
  try {
    const stored: Stored = { code: room.code, role: room.role, at: now };
    localStorage.setItem(KEY, JSON.stringify(stored));
  } catch {
    // Переполненное или закрытое хранилище не должно ронять вход в комнату:
    // без записи игрок просто теряет право на переподключение, а не игру.
  }
}

/**
 * Забыть комнату.
 *
 * Зовётся, когда игрок вышел САМ. Это и есть разница между «связь оборвалась» и
 * «я ушёл»: первое обязано восстанавливаться, второе — нет, иначе кнопка
 * «назад» возвращала бы в ту же комнату при следующем открытии экрана.
 */
export function clearRoom(): void {
  try {
    localStorage.removeItem(KEY);
  } catch {
    // Нечего чистить — нечего и падать.
  }
}
