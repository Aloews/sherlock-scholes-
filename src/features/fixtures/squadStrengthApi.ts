import { supabase } from '@/shared/lib/supabase';

/**
 * Уровень состава команд матча — по известности их игроков.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Просили ИИ-разбор истории противостояний. Строить его
 * не из чего, и это измерено: 0 из 266 предстоящих матчей имеют хоть одну
 * прошлую встречу, на команду в среднем 1.1 сыгранный матч. Замена, которую
 * выбрал владелец: оценивать команды по уровню состава.
 *
 * ⚠️ ЧТО ЭТО ЗА ЧИСЛО И ЧЕМ ОНО НЕ ЯВЛЯЕТСЯ. Это средняя ИЗВЕСТНОСТЬ игроков
 * (`cards.fame`, 0..100, построена по просмотрам в википедии). Известность —
 * не мастерство и не форма: ветеран на излёте известнее сильного дебютанта.
 * Поэтому на экране это подписано «состав», а не «сила», и рядом стоит, по
 * скольким игрокам посчитано.
 *
 * ⚠️ И ЭТО НЕ ПРОГНОЗ. Ни вероятности, ни «фаворита», ни выделенной стороны —
 * см. шапку FixtureCard: коэффициентов в этом проекте нет и быть не может.
 * Здесь другое происхождение (свои же карточки, а не букмекер), но выдавать
 * известность за предсказание нельзя тем более.
 */
export interface SquadStrength {
  fixture_id: string;
  /** Средняя известность 0..100 по `depth` самым известным игрокам хозяев. */
  home_fame: number;
  away_fame: number;
  /**
   * По скольким игрокам с КАЖДОЙ стороны посчитано.
   *
   * ⚠️ Равная глубина — не придирка, а исправление перекоса. Клубы оцифрованы
   * неравномерно: у «Реала» 20 карточек, у «Реала Сосьедад» 5, и у бедно
   * оцифрованного в карточки попали только знаменитости. Наивное среднее по
   * всем сравнивало бы ВЕСЬ состав одного со ЗВЁЗДАМИ другого. Замер:
   * «Арсенал» по всем карточкам 87.7, по одиннадцати лучшим — 97.1.
   */
  depth: number;
  /** Сколько карточек у клуба всего — показывает, насколько оценка полная. */
  home_squad: number;
  away_squad: number;
}

/**
 * ⚠️ ВОЗВРАЩАЕТ ДАЛЕКО НЕ ПО ВСЕМ МАТЧАМ, и это нормально, а не поломка.
 * Замер 25.08.2026: из 268 предстоящих матчей обе команды оцифрованы хотя бы
 * по пять игроков только у 23. Экран обязан молчать там, где числа нет, а не
 * показывать ноль или прочерк: «уровень состава 0» читается как «слабый
 * состав», хотя значит «мы не знаем».
 *
 * Отказ возвращает пустую карту, а не бросает: раздел необязательный, и
 * ронять из-за него список матчей нельзя.
 */
export async function fetchSquadStrength(): Promise<Map<string, SquadStrength>> {
  const { data, error } = await supabase.rpc('fixture_squad_strength', { p_min_depth: 5 });
  if (error) {
    console.error('[fixtures] fixture_squad_strength failed:', error.code, error.message);
    return new Map();
  }
  const map = new Map<string, SquadStrength>();
  for (const row of (data as SquadStrength[]) ?? []) map.set(row.fixture_id, row);
  return map;
}
