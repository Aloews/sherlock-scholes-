// Состав клуба — ОДИН ответ на вопрос «кто за него играет», общий для экрана
// матча и экрана команды. Клиентская половина supabase/migrations/
// squads_everywhere_value.sql.
//
// ⚠️ ДВЕ ФУНКЦИИ, ОТВЕЧАВШИЕ НА ОДИН ВОПРОС, РАЗОШЛИСЬ МОЛЧА. Экран матча шёл
// в `club_squad` (наши карточки), экран команды умел ещё и заявку с
// Transfermarkt. У «Брайтона» в заявке 30 человек — под матчем не было ни
// одного. Теперь источник один и тот же, и порядок источников назван в базе.

import { supabase } from '@/shared/lib/supabase';

export interface SquadPlayer {
  /** null — человек есть в заявке клуба, а карточки в колоде у него нет. */
  card_id: string | null;
  /** Имя как в источнике: у заявки латиницей, у карточки по-русски. */
  name: string;
  name_en: string | null;
  /**
   * Рыночная стоимость в евро. ЭТО И ЕСТЬ МЕРА УРОВНЯ НА ЭКРАНЕ.
   *
   * ⚠️ Владелец: «пиши стоимость игрока, а не наш рейтинг, у нашего рейтинга
   * все футболисты имеют по 100. Стоимость точнее отражает уровень игрока».
   * Это не вкусовщина, это видно в самих числах: у состава «Брайтона» наш
   * `level` даёт 96–99 всем подряд, а стоимости идут от 60 до 2 млн.
   *
   * null — игрока не оценили. Ноль читался бы как «не стоит ничего».
   */
  market_value_eur: number | null;
  /** 'Goalkeeper' | 'Defender' | 'Midfield' | 'Attack' — как отдаёт источник. */
  player_position: string | null;
  shirt_number: number | null;
  photo_url: string | null;
  /**
   * 'roster' | 'cards' | 'soccerwiki' — ЧЕМ отвечено, и это подписывается.
   * «Состав из заявки клуба» и «состав из наших карточек» — разные
   * утверждения: в первом весь клуб, во втором только оцифрованные.
   */
  source: string;
}

/**
 * Состав ОДНОГО клуба — тем же ответом, что и составы матча.
 *
 * ⚠️ ОДНА ФУНКЦИЯ БАЗЫ НА ОБА ЭКРАНА (`club_squad_view`), и это не экономия.
 * Владелец: «экран „команды и статистика“ синхронизируй с функцией „показать
 * составы“». До этого экран матча ходил в `club_squad` (наши карточки), а
 * экран клуба умел ещё и заявку с Transfermarkt: два ответа на один вопрос
 * расходились молча — у «Брайтона» в заявке 30 человек, а под матчем не было
 * ни одного.
 *
 * Отказ возвращает пустой список, а не бросает: состав раскрывается по
 * нажатию и ронять из-за него список команд нельзя.
 */
export async function fetchClubSquadView(
  clubKey: string,
  limit = 40,
): Promise<SquadPlayer[]> {
  const { data, error } = await supabase.rpc('club_squad_view', {
    p_club_key: clubKey,
    p_limit: limit,
  });
  if (error) {
    console.error('[club_squad_view]', error.code ?? '', error.message);
    return [];
  }
  return (data as SquadPlayer[]) ?? [];
}
