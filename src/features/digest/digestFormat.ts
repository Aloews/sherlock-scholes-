// Чистая часть дайджеста: то, что можно проверить, не поднимая сети.
//
// Отдельным модулем, а не рядом с вызовами RPC, по прямой причине:
// digestApi.ts импортирует клиент Supabase, а тот падает на старте без
// VITE_-переменных — то есть любой тест на две строчки арифметики требовал бы
// поднятого окружения. Разделение здесь не ради красоты слоёв, а ради того,
// чтобы эти функции вообще были покрыты.

/** Одна карточка ролика — ровно то, что нужно для ссылки. */
export interface ClipRef {
  video_id: string;
}

/** Ссылка на ролик. Строится здесь, потому что в базе лежит только id. */
export function watchUrl(clip: ClipRef): string {
  return `https://www.youtube.com/watch?v=${clip.video_id}`;
}

/**
 * Язык, на котором просить ленту.
 *
 * i18next отдаёт то, что ему настроили, и это не всегда двухбуквенный код:
 * «ru-RU» и «pt-BR» — законные значения, а в базе языки лежат как «ru» и «pt».
 * Передать туда «ru-RU» значит не совпасть ни с одной строкой и получить
 * чистый английский — экран, который выглядит рабочим и показывает не то.
 */
export function feedLanguage(i18nLanguage: string): string {
  return (i18nLanguage || 'en').slice(0, 2).toLowerCase();
}
