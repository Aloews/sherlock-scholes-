import type { NewsItem } from './digestApi';
import { storyTokens, overlap, SAME_STORY_TOKENS } from './storyTokens';

/**
 * Сюжет — несколько заметок об одном событии, склеенные в одну карточку.
 */
export interface Story {
  /** Заметка, которую показываем. Выбор объяснён в pickLead. */
  lead: NewsItem;
  /** Остальные издания того же сюжета, без дубликатов, в порядке появления. */
  alsoSources: string[];
  /** Сколько ВСЕГО изданий в сюжете, включая ведущее. */
  sourceCount: number;
}

/**
 * Кого показывать из сюжета.
 *
 * ⚠️ ЯЗЫК ЧИТАТЕЛЯ ВАЖНЕЕ КАРТИНКИ. Сюжет почти всегда двуязычный: свои
 * издания и англоязычные. Показать англичанина русскоязычному ради картинки
 * значит отдать ему заголовок, который он не прочитает, — а картинка
 * подписи не заменяет.
 *
 * Дальше — картинка: у 76% заметок она есть, и карточка с ней читается
 * заметно живее. Потом свежесть.
 */
function pickLead(items: NewsItem[], lang: string): NewsItem {
  const score = (n: NewsItem) =>
    (n.lang === lang ? 4 : 0) + (n.image_url ? 2 : 0);
  return [...items].sort((a, b) =>
    score(b) - score(a)
    || Date.parse(b.published_at) - Date.parse(a.published_at))[0];
}

/**
 * Насколько сильно заголовки обязаны совпасть, чтобы считаться одним сюжетом.
 *
 * ⚠️ ОДНОГО АБСОЛЮТНОГО ПОРОГА МАЛО, И ЭТО ПРОВЕРЕНО НА ЖИВОЙ ЛЕНТЕ. При
 * правиле «три общие основы» в один сюжет слиплись ДВАДЦАТЬ заметок из
 * шестидесяти: Селтик — ЛАСК, Будё-Глимт — НЕК, Сабах — Хапоэль, АЕК и даже
 * «Бетис» — «Валенсия» из Ла Лиги. Совпадали не события, а футбольный
 * словарь — «лиги чемпионов», «разгромил», «тренер», «матче».
 *
 * Доля от МЕНЬШЕГО заголовка это лечит: три общих слова из семи — сюжет, три
 * из восемнадцати — совпадение словаря.
 */
export const SAME_STORY_FRACTION = 0.45;

/**
 * Склеить ленту в сюжеты.
 *
 * ЗАЧЕМ. Сервер считает `loudness` — сколько изданий вышло с тем же сюжетом, —
 * но не говорит, какие именно заметки в него попали, и лента печатает один
 * трансфер пятью строками подряд. Отсюда и ощущение «сухо»: дело не в
 * оформлении, а в повторах.
 *
 * ⚠️ ЗВЕЗДА, А НЕ СВЯЗНЫЕ КОМПОНЕНТЫ. Первая версия склеивала объединением
 * множеств — «A похожа на B, B на C, значит все трое об одном». Похожесть
 * заголовков НЕ транзитивна, и на живой ленте эта цепочка стянула двадцать
 * разных матчей в одну карточку: девятнадцать новостей исчезли бы с экрана.
 *
 * Теперь сюжет строится вокруг ОДНОЙ заметки: берём первую нераспределённую
 * (лента уже отсортирована сервером по громкости) и подбираем к ней всё
 * похожее НА НЕЁ. Цепочки не возникает. Это ещё и та же форма, в которой
 * сервер считает `loudness`, — он тоже смотрит соседей одной заметки, а не
 * компоненты связности.
 *
 * ⚠️ ЧИСЛО НА КАРТОЧКЕ — СВОЁ, а не серверное `loudness`. Здесь правило
 * строже (добавлена доля), поэтому изданий в сюжете может оказаться меньше,
 * чем насчитал сервер. Показываем то, что реально склеили: иначе рядом
 * встанут «6 изданий» и четыре названия.
 *
 * Порядок сюжетов — серверный: лента уже отсортирована по громкости и
 * свежести, и пересортировывать её здесь значило бы решать за сервер.
 */
export function groupStories(items: readonly NewsItem[], lang: string): Story[] {
  const toks = items.map((n) => storyTokens(n.title));
  const used = new Array(items.length).fill(false);
  const out: Story[] = [];

  for (let i = 0; i < items.length; i += 1) {
    if (used[i]) continue;
    used[i] = true;
    const group: NewsItem[] = [items[i]];

    for (let j = i + 1; j < items.length; j += 1) {
      if (used[j]) continue;
      const common = overlap(toks[i], toks[j]);
      // Пустой заголовок дал бы деление на ноль; `|| 1` делает долю нулевой,
      // то есть такая заметка останется отдельным сюжетом, а не приклеится ко
      // всему подряд.
      const smaller = Math.min(toks[i].size, toks[j].size) || 1;
      if (common >= SAME_STORY_TOKENS && common / smaller >= SAME_STORY_FRACTION) {
        used[j] = true;
        group.push(items[j]);
      }
    }

    const lead = pickLead(group, lang);
    const seen = new Set<string>([lead.source]);
    const alsoSources: string[] = [];
    for (const n of group) {
      if (seen.has(n.source)) continue;
      seen.add(n.source);
      alsoSources.push(n.source);
    }
    out.push({ lead, alsoSources, sourceCount: seen.size });
  }

  return out;
}
