/**
 * Суть под заголовком показывается, только если она что-то ДОБАВЛЯЕТ.
 *
 * Владелец: «раскрытие новости точное такое же как заголовок, убери либо
 * добавляй детали, которые не были описаны в заголовке».
 *
 * ⚠️ ЭТО НЕ ЛЕЧИТСЯ ПОДСКАЗКОЙ МОДЕЛИ, и это важно понять до правки. Модель
 * пересказывает `description` из RSS, а у русских лент этот description сам
 * является пересказом заголовка. Просить «добавь деталей» — значит просить
 * выдумать их: тех фактов нет ни в одном тексте, который модель видит.
 * Поэтому единственный честный ход — не писать ничего.
 *
 * ЗАМЕР 03.09.2026 на живой ленте (60 заметок на язык):
 *
 *   ru   44 с сутью, из них 7 добавляют меньше четырёх новых слов
 *   en   20 с сутью, минимум новизны — ШЕСТЬ слов, под порог не попадает ни одна
 *
 * То есть правило бьёт ровно по той ленте, на которую жаловались, и не
 * трогает ту, что и так пишет по делу. Вот вся семёрка, по которой выбран
 * порог, — новизна в них это глаголы речи и ничего больше:
 *
 *   0  «Андрей Мостовой перешёл в „Локомотив“ на правах аренды»
 *      → «Андрей Мостовой перешёл в „Локомотив“ на правах аренды.»
 *   1  «Моуринью — о решении Месси завершить карьеру в сборной»
 *      → «Моуринью прокомментировал решение Месси завершить карьеру…»   (+прокомментировал)
 *   2  «Тренер „ПСЖ“ Энрике — о переходе Барколя в „Ливерпуль“»
 *      → «Энрике прокомментировал переход Барколы…»            (+прокомментировал, +заявив)
 *
 * ⚠️ ПОЧЕМУ НЕ `storyTokens`, ХОТЯ ОН РЯДОМ И ДЕЛАЕТ ПОХОЖЕЕ. Тот токенайзер
 * написан для СКЛЕЙКИ СЮЖЕТОВ и намеренно выбрасывает числа и слова короче
 * четырёх букв. Здесь это ровно наоборот: «50», «2028», «3 сентября» — и есть
 * та деталь, которой в заголовке не было. Взять готовое значило бы не увидеть
 * единственное, что суть добавляет. Замер это подтвердил: со `storyTokens`
 * под правило попадала 1 заметка из 44 вместо семи.
 *
 * Порог считает СЛОВА, а не ищет глаголы речи списком. Список пришлось бы
 * вести на девяти языках, и он разошёлся бы с ними молча; счёт работает на
 * любом языке одинаково.
 */

/**
 * Стоп-слова — только служебные, одинаково бессодержательные во всех лентах.
 * Здесь НЕТ глаголов речи: они отсекаются порогом, а не перечислением, иначе
 * список пришлось бы держать на девяти языках.
 */
const STOP = new Set(
  ('и в во не на что он а то как из по за от до для о с со у же это все её его их'
   + ' к но бы был была было были есть быть'
   + ' will was were the a an of to in on at for and or with his her its their'
   + ' that this has have had after').split(/\s+/),
);

/**
 * Слова сути для сравнения с заголовком.
 *
 * Числа сохраняются ЦЕЛИКОМ и не обрезаются: «2028» и «2026» обязаны
 * различаться, а обрезка до пяти знаков сделала бы их одним токеном на любой
 * длине года. Слова обрезаются до пяти — так «переход» встречается с
 * «переходе», без словаря словоформ.
 */
export function leadTokens(text: string): Set<string> {
  const out = new Set<string>();
  for (const w of text.toLowerCase().split(/[^\p{L}\p{N}]+/u)) {
    if (!w || STOP.has(w)) continue;
    out.add(/^\d+$/.test(w) ? w : w.slice(0, 5));
  }
  return out;
}

/**
 * Порог новизны: меньше четырёх новых слов — это пересказ заголовка.
 *
 * Четыре, а не три: при трёх под правило попадала «Ольмо — о позиции
 * „Атлетико“ по переходу Альвареса» → «Ольмо прокомментировал ОТКАЗ
 * „Атлетико“ ПРОДАВАТЬ Альвареса», где новизна — «прокомментировал, отказ,
 * продавать»: два из трёх слов несут смысл, которого в заголовке нет.
 */
export const MIN_NEW_WORDS = 4;

/**
 * Добавляет ли суть хоть что-то к заголовку. Пустая суть — не добавляет.
 */
export function leadAddsDetail(title: string, lead: string | null | undefined): boolean {
  if (!lead || !lead.trim()) return false;
  const inTitle = leadTokens(title);
  let fresh = 0;
  for (const w of leadTokens(lead)) {
    if (!inTitle.has(w)) {
      fresh += 1;
      if (fresh >= MIN_NEW_WORDS) return true;
    }
  }
  return false;
}
