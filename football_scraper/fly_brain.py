#!/usr/bin/env python3
"""Грибовидное тело дрозофилы на настоящем коннектоме — прогнозист матчей.

⚠️ ЭТОТ ФАЙЛ НАПИСАН ВЗАМЕН ПОДДЕЛКИ, И НАЧАТЬ НАДО С НЕЁ. В `/duel` под
именем «мозг дрозофилы» стояла резервуарная сеть: случайная разрежённая
матрица `rng.normal(...)` плюс гребневая регрессия. Разрежённость была взята
«по мотивам» мухи, и на этом сходство кончалось — ни одной настоящей связи,
ни одного дофаминового нейрона, никакого подкрепления. Название было красивее
сути. Владелец спросил прямо: «ты действительно скачал оцифрованный мозг
дрозофилы и сделал так, чтобы он получал дофамин от угаданного исхода?» — и
честный ответ был «нет».

ЗДЕСЬ — ДА, И ВОТ ЧТО ИМЕННО.

СВЯЗИ НАСТОЯЩИЕ. `connectome/mb_connectome.npz` вырезан из выгрузки hemibrain
v1.2 (Janelia, neuprint): 21 739 прослеженных нейронов, 3 550 403 пары с
ЧИСЛОМ СИНАПСОВ. Взято грибовидное тело целиком — 132 проекционных нейрона,
1927 клеток Кеньона, 68 выходных MBON, 301 дофаминовый нейрон награды (PAM),
16 наказания (PPL1) и единственный тормозный APL. Происхождение и проверки —
в `connectome/extract_mushroom_body.py`.

ПРАВИЛО ОБУЧЕНИЯ НАСТОЯЩЕЕ. У мухи пластичен синапс KC→MBON, и меняет его
СОВПАДЕНИЕ двух вещей: клетка Кеньона активна И в этот компартмент пришёл
дофамин. Результат — ДЕПРЕССИЯ этого синапса (Hige 2015, Cohn 2015). Не рост,
а именно ослабление: муха учится не «хотеть сильнее», а «перестать слушать
тот выход, который уводил не туда».

ВАЛЕНТНОСТЬ БЕРЁТСЯ ИЗ КОМПАРТМЕНТА, А НЕ ИЗ ЗНАКА. Компартменты, куда ходят
PAM (награда), держат MBON, гонящие ПРОЧЬ; ослабь их — получится приближение.
Компартменты PPL1 (наказание) держат MBON, зовущие К; ослабь их — получится
избегание. Поэтому одно и то же правило депрессии даёт оба знака обучения, и
никакого «градиента» здесь нет вовсе.

ЧЕГО ЗДЕСЬ ЧЕСТНО НЕТ. У мухи нет исходов футбольных матчей, поэтому
соответствие «компартмент → исход» назначено нами (по алфавиту, по кругу) и
записано в `outcome_compartments`. Это единственное произвольное место, и оно
намеренно вынесено в одну функцию, чтобы его было видно.

    from fly_brain import FlyBrain
    fly = FlyBrain.load()
    p = fly.predict(features)          # 'H' | 'D' | 'A'
    fly.learn(features, actual='H')    # дофамин по факту матча
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass, field

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
CONNECTOME = os.path.join(HERE, "connectome")

OUTCOMES = ("H", "D", "A")

# ⚠️ ДОЛЯ АКТИВНЫХ КЛЕТОК КЕНЬОНА — ИЗМЕРЕННАЯ БИОЛОГИЯ, А НЕ РУЧКА НАСТРОЙКИ.
# На один запах в грибовидном теле отвечает около 5 % KC; разрежённость держит
# единственный тормозный нейрон APL. Поставь 50 % — и код Кеньона перестанет
# быть кодом: каждый вход будет похож на каждый.
KC_SPARSITY = 0.05

# Скорость депрессии: доля, на которую дофамин ослабляет синапс за одно
# совпадение. У мухи одно сочетание запаха с сахаром уже меняет поведение, но
# не до нуля.
DEPRESSION = 0.05

# Пол синапса. Депрессия не уводит вес в ноль совсем: полностью умерший синапс
# больше никогда не участвует, и брать его обратно нечем.
FLOOR = 0.2

# ⚠️ ЗАБЫВАНИЕ ПРОБОВАЛИ И НЕ ВЗЯЛИ — НЕ ПОВТОРЯЙТЕ БЕЗ ЗАМЕРА. Депрессия
# односторонняя, и это выглядит поломкой: в бою на 15.09.2026 при 3620 учениях
# 43.4 % всех синапсов, которых обучение вообще касалось, уже лежали на полу, а
# синапс на полу не двигается больше никогда. Напрашивается возврат к
# коннектому — у мухи память и правда угасает сама.
#
# Замер сказал обратное, трижды.
#
# 1. ПОЛ РАСТЁТ ЛОГАРИФМОМ И ВЫХОДИТ НА ПОЛКУ. Обучение на РАЗНЫХ матчах по
#    одному разу (ровно то, что делает бой): 250 учений — 3.3 %, 500 — 15.6 %,
#    1000 — 30.0 %, 1500 — 35.3 %, 2000 — 39.5 %, 2713 — 41.7 %. Прибавка
#    падает 12.3 → 14.4 → 5.3 → 4.2 → 2.2. Замирания нет, боевые 43.4 % лежат
#    на этой самой кривой.
# 2. ТОЧНОСТЬ НА ЭТОМ УЧАСТКЕ РОВНАЯ. 0.436 → 0.460 → 0.476 → 0.472 → 0.474 →
#    0.461 при парной ошибке около 1.5 п.п. — разброс не выходит за неё.
# 3. ВОЗВРАТ К КОННЕКТОМУ СТИРАЕТ ПАМЯТЬ. Шаг `w += r * (w0 - w)` на каждом
#    учении при r от 0.001 схлопывал муху до одного-двух исходов на весь тест и
#    ровно базовой точности 0.436. Причина не в величине: угасание у мухи идёт
#    по ВРЕМЕНИ, а шаг на учение делает его зависимым от того, как часто
#    учат, — чаще учишь, быстрее забывает, что задом наперёд.
#
# Падение 0.461 → 0.379 действительно есть, но у него другая причина: это
# ДВАДЦАТЬ проходов по одной и той же выборке, то есть переобучение, а не
# объём. Гомеостаз (снятое у горевших клеток отдать негоревшим) пол убирает
# начисто — 4.2 % вместо 79.7 %, — а падение оставляет: 0.358 к двадцатому
# проходу. Значит лечили не ту болезнь.
#
# Инструмент, которым это померено, остался: `floored_fraction`.


def _load_npz() -> dict:
    z = np.load(os.path.join(CONNECTOME, "mb_connectome.npz"))
    return {k: z[k] for k in z.files}


def _load_meta() -> dict:
    with open(os.path.join(CONNECTOME, "mb_meta.json")) as f:
        return json.load(f)


def outcome_compartments(meta: dict) -> dict[str, dict[str, list[int]]]:
    """Какие MBON отвечают за какой исход.

    ⚠️ ЕДИНСТВЕННОЕ ПРОИЗВОЛЬНОЕ МЕСТО ВО ВСЁМ ФАЙЛЕ, И ОНО ЗДЕСЬ НАРОЧНО, А НЕ
    размазано по коду. У мухи нет «хозяев, ничьей и гостей»; компартменты
    раздаются исходам по кругу в алфавитном порядке — детерминированно и без
    подглядывания в данные.

    Разделение на `push` и `pull` — НЕ произвол, а анатомия: компартмент, куда
    ходит PAM (награда), и компартмент, куда ходит PPL1 (наказание), дают
    противоположное поведение при одной и той же депрессии.

    ⚠️ СРАВНИВАТЬ ИМЕНА ЦЕЛИКОМ НЕЛЬЗЯ, И ЭТО НЕ ПРИДИРКА. Дофаминовый нейрон
    сидит в ОДНОМ компартменте (`y5`, `B'2a`, `a'3`), а выходной тянется через
    несколько (`y5B'2a`, `B2y5`, `y1pedc>a/B`). Точное равенство давало 12 MBON
    из 68 — пять шестых грибовидного тела просто не участвовали. По вхождению
    имени — 43, и они раскладываются по трём исходам ровно (8 «прочь» и 6–7
    «к» на каждый).
    """
    dan_comp: dict[str, set[str]] = {"reward": set(), "punish": set()}
    for d in meta["dan"]:
        if d["comp"]:
            dan_comp[d["valence"]].add(d["comp"])

    def hits(mbon_comp: str, comps: set[str]) -> int:
        return sum(1 for c in comps if c in mbon_comp)

    push: list[tuple[str, int]] = []   # MBON компартментов награды — гонят ПРОЧЬ
    pull: list[tuple[str, int]] = []   # MBON компартментов наказания — зовут К
    for i, m in enumerate(meta["mbon"]):
        c = m["comp"]
        if not c:
            continue
        r, p = hits(c, dan_comp["reward"]), hits(c, dan_comp["punish"])
        if r == 0 and p == 0:
            continue
        # Выход, дотянувшийся до обоих, отдаётся тому, чьих нейронов больше;
        # при равенстве — наказанию: PPL1 их всего 16 на 301 PAM, и без этого
        # перевеса сторона «зовут К» осталась бы почти пустой.
        (push if r > p else pull).append((c, i))

    out: dict[str, dict[str, list[int]]] = {o: {"push": [], "pull": []} for o in OUTCOMES}
    for side, rows in (("push", push), ("pull", pull)):
        for k, (_c, i) in enumerate(sorted(rows)):
            out[OUTCOMES[k % len(OUTCOMES)]][side].append(i)
    return out


# ⚠️ ПРИЗНАКИ И ИХ ПОТОЛКИ — ЗДЕСЬ, А НЕ РАЗМАЗАНЫ ПО ВЫЗЫВАЮЩЕМУ КОДУ. Вход
# мухи — «концентрация запаха», число от 0 до 1. Голы за матч и доли побед
# живут в разных единицах, и делить их на одно число значило бы сказать мозгу,
# что 0.5 гола и 50 % побед — это одно и то же.
ODOUR: tuple[tuple[str, float], ...] = (
    ("h_gf", 4.0), ("h_ga", 4.0), ("a_gf", 4.0), ("a_ga", 4.0),
    ("h_wr", 1.0), ("a_wr", 1.0), ("h_dr", 1.0), ("a_dr", 1.0),
    # ⚠️ ФОРМА ДОМА И В ГОСТЯХ ОТДЕЛЬНО. Общее среднее по всем матчам прячет
    # команду, которая дома громит, а на выезде не забивает, — а именно это и
    # решает исход конкретного матча.
    ("h_home_gf", 4.0), ("h_home_ga", 4.0), ("h_home_wr", 1.0),
    ("a_away_gf", 4.0), ("a_away_ga", 4.0), ("a_away_wr", 1.0),
)


def row_to_odour(row) -> list[float]:
    """Строка `duel_features` → вход мухи, каждый признак в своих единицах."""
    out = []
    for name, top in ODOUR:
        v = row.get(name)
        out.append(0.0 if v is None else float(np.clip(float(v) / top, 0.0, 1.0)))
    return out


def encode_odour(x, n_pn: int) -> np.ndarray:
    """Признаки (уже 0..1) → активность проекционных нейронов.

    ⚠️ ЭТО ПЕРЕВОДЧИК, А НЕ МОДЕЛЬ, и он нарочно тупой. У мухи на входе запах:
    сколько-то гломерул горит сильнее, сколько-то слабее. Признак раскладывается
    по своей полосе гломерул «термометром»: чем больше значение, тем больше
    гломерул в полосе горит. Никакого обучения здесь нет и быть не должно —
    иначе вход перестанет быть входом и начнёт решать за мозг.
    """
    x = np.asarray(x, dtype=float).ravel()
    pn = np.zeros(n_pn, dtype=float)
    band = max(1, n_pn // len(x))
    for k, v in enumerate(x):
        lo = k * band
        hi = min(n_pn, lo + band)
        if lo >= n_pn:
            break
        t = float(np.clip(v, 0.0, 1.0))
        lit = int(t * (hi - lo))
        pn[lo:lo + lit] = 1.0
        if lo + lit < hi:                       # частично зажжённая гломерула
            pn[lo + lit] = t * (hi - lo) - lit
    return pn


@dataclass
class FlyBrain:
    """Грибовидное тело: вход → разрежённый код → выход, с дофамином."""

    pn_kc: np.ndarray                      # (n_pn, n_kc) число синапсов
    kc_mbon: np.ndarray                    # (n_kc, n_mbon) ПЛАСТИЧНЫЕ веса
    kc_mbon0: np.ndarray                   # исходные — чтобы видеть, что выучено
    apl_kc: np.ndarray                     # (n_kc,) сила торможения от APL
    groups: dict[str, dict[str, list[int]]]
    meta: dict = field(repr=False, default_factory=dict)
    taught: int = 0
    # Сила подкрепления: доля, на которую дофамин ослабляет синапс за одно
    # совпадение. Значение по умолчанию — `DEPRESSION`; протокол обучения
    # вправе его менять, архитектуру — нет.
    depression: float = DEPRESSION

    # ── сборка ───────────────────────────────────────────────────────────────
    @classmethod
    def load(cls) -> "FlyBrain":
        z, meta = _load_npz(), _load_meta()
        n_pn, n_kc, n_mb = len(meta["pn"]), len(meta["kc"]), len(meta["mbon"])
        pn_kc = np.zeros((n_pn, n_kc), dtype=float)
        pn_kc[z["pn_kc_row"], z["pn_kc_col"]] = z["pn_kc_w"]
        kc_mbon = np.zeros((n_kc, n_mb), dtype=float)
        kc_mbon[z["kc_mbon_row"], z["kc_mbon_col"]] = z["kc_mbon_w"]
        apl = z["apl_kc"].astype(float)
        return cls(pn_kc=pn_kc, kc_mbon=kc_mbon, kc_mbon0=kc_mbon.copy(),
                   apl_kc=apl / (apl.max() or 1.0),
                   groups=outcome_compartments(meta), meta=meta)

    # ── прямой ход ───────────────────────────────────────────────────────────
    def kenyon(self, pn: np.ndarray) -> np.ndarray:
        """Разрежённый код: APL оставляет гореть около 5 % клеток.

        ⚠️ ТОРМОЖЕНИЕ ЗДЕСЬ ГЛОБАЛЬНОЕ, И ЭТО НЕ УПРОЩЕНИЕ. APL в грибовидном
        теле ОДИН на всё тело: он собирает возбуждение со всех KC и возвращает
        его всем обратно. Поэтому порог не задан числом, а получается сам —
        ровно так, как работает нормализация у мухи.
        """
        drive = pn @ self.pn_kc
        k = max(1, int(round(KC_SPARSITY * drive.size)))
        # Торможение пропорционально собственной связи KC с APL: клетки,
        # сидящие на APL плотнее, гасятся сильнее.
        drive = drive - self.apl_kc * drive.sum() / drive.size
        if not np.any(drive > 0):
            return np.zeros_like(drive)
        cut = np.partition(drive, -k)[-k]
        return (drive >= cut).astype(float) * (drive > 0)

    def mbon(self, kc: np.ndarray) -> np.ndarray:
        return kc @ self.kc_mbon

    def scores(self, x) -> dict[str, float]:
        """Чем МЕНЬШЕ, тем привлекательнее исход — как у мухи.

        `push` — выходы из компартментов награды, они гонят ПРОЧЬ; `pull` —
        из компартментов наказания, они зовут К. Обучение только ослабляет,
        поэтому «выученный» исход узнаётся по упавшему `push`.

        ⚠️ КАЖДАЯ ГРУППА СРАВНИВАЕТСЯ СО СВОИМ ЖЕ ИСХОДНЫМ ОТКЛИКОМ, И БЕЗ
        ЭТОГО МОЗГ НЕ РАБОТАЕТ ВОВСЕ. Компартменты разного размера: у одного
        выходного нейрона десятки тысяч синапсов от KC, у другого сотни. Пока
        суммы сравнивались напрямую, побеждала та группа, которой досталось
        меньше синапсов, — и ответ не менялся от матча к матчу. Замер: 32.5 %
        и один и тот же исход на все 1961 матч. С делением на собственную
        основу — 42.2 % и три разных ответа.

        То есть меряется не «сколько шумит компартмент», а НАСКОЛЬКО ОН
        ПРОСЕЛ по сравнению с тем, как он же отвечал до обучения на этот
        самый код Кеньона.
        """
        kc = self.kenyon(encode_odour(x, self.pn_kc.shape[0]))
        now, was = kc @ self.kc_mbon, kc @ self.kc_mbon0
        out = {}
        for o, g in self.groups.items():
            push = now[g["push"]].sum() / (was[g["push"]].sum() or 1.0)
            pull = now[g["pull"]].sum() / (was[g["pull"]].sum() or 1.0)
            out[o] = float(push - pull)
        return out

    def predict(self, x) -> str:
        s = self.scores(x)
        return min(OUTCOMES, key=lambda o: s[o])

    # ── дофамин ──────────────────────────────────────────────────────────────
    def learn(self, x, actual: str) -> None:
        """Пришёл исход — пришёл дофамин.

        ⚠️ ПРАВИЛО ОДНО, И ОНО НЕ ЗНАЕТ, ЧТО МУХА НАЗВАЛА. Дофаминовый нейрон
        отвечает на ПОДКРЕПЛЕНИЕ, а не на ошибку предсказания: у мухи сахар
        включает PAM независимо от того, чего она ждала. Совпадение «клетка
        Кеньона горела» и «в компартмент пришёл дофамин» ОСЛАБЛЯЕТ синапс
        KC→MBON — и только его, только у горевших клеток.

        Сбылось `actual` → PAM в его компартменты награды → падает `push`
        этого исхода → в следующий раз похожий матч он назовёт охотнее.

        ⚠️ ВЕТКА «НАКАЗАТЬ ЗА ОШИБКУ» БЫЛА И УБРАНА, ПРИЧЁМ ЗАМЕР СОШЁЛСЯ С
        БИОЛОГИЕЙ. Добавка «названо мимо → PPL1 в компартменты названного»
        выглядела разумно, но это обучение по ошибке предсказания, которого у
        мухи нет. На тех же данных она давала 33.6 % против 42.2 % у чистого
        подкрепления. Правило, списанное с мухи, оказалось и точнее
        придуманного.
        """
        if actual not in self.groups:
            raise ValueError(f"неизвестный исход {actual!r}")
        kc = self.kenyon(encode_odour(x, self.pn_kc.shape[0]))
        active = kc > 0
        if not active.any():
            return
        cols = np.array(self.groups[actual]["push"], dtype=int)
        if cols.size:
            block = self.kc_mbon[np.ix_(active, cols)]
            floor = self.kc_mbon0[np.ix_(active, cols)] * FLOOR
            self.kc_mbon[np.ix_(active, cols)] = np.maximum(
                block * (1.0 - self.depression), floor)
        self.taught += 1

    # ── состояние ────────────────────────────────────────────────────────────
    def nonzero_index(self):
        """Адреса синапсов, которые есть в коннектоме.

        ⚠️ ПАМЯТЬ СОХРАНЯЕТСЯ ТОЛЬКО ПО НИМ, И ЭТО НЕ ЭКОНОМИЯ. Матрица
        KC→MBON — 1927 × 68, но связей в ней 30 496: остальное — нули, которых
        у мухи нет вовсе. Сохранять нули значило бы позволить им однажды стать
        ненулями и завести синапс, которого в мозге не существует.

        Порядок берётся из самого коннектома и потому одинаков при каждой
        загрузке — сохранённый вектор ложится обратно ровно туда, откуда взят.
        """
        return np.nonzero(self.kc_mbon0)


    def floored_fraction(self) -> float:
        """Доля ТРОНУТЫХ синапсов, лежащих на полу.

        Именно она, а не `learned_fraction`, показывает исчерпание: синапс на
        полу не двинется больше никогда, сколько его ни учи.
        """
        live = self.kc_mbon0 > 0
        touched = live & (self.kc_mbon < self.kc_mbon0 - 1e-12)
        if not touched.any():
            return 0.0
        floored = touched & (self.kc_mbon <= self.kc_mbon0 * FLOOR * (1 + 1e-9))
        return round(float(floored.sum()) / float(touched.sum()), 4)

    def learned_fraction(self) -> float:
        """Насколько веса уехали от коннектома. 0 — ничему не учился."""
        base = self.kc_mbon0.sum() or 1.0
        return float(1.0 - self.kc_mbon.sum() / base)

    def save(self, path: str) -> None:
        np.savez_compressed(path, kc_mbon=self.kc_mbon.astype(np.float32),
                            taught=np.array([self.taught]))

    def restore(self, path: str) -> None:
        z = np.load(path)
        self.kc_mbon = z["kc_mbon"].astype(float)
        self.taught = int(z["taught"][0])
