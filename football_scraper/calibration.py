#!/usr/bin/env python3
"""Калибровка уверенности: превратить «уверен на 79 %» в число, которому можно верить.

⚠️ ЗАЧЕМ ЭТО ВООБЩЕ, ЕСЛИ ТОЧНОСТЬ НЕ РАСТЁТ. Калибровка НЕ делает прогнозы
лучше. Она не меняет НИ ОДНОГО выбранного исхода: преобразование монотонно,
порядок матчей по уверенности остаётся прежним. Меняется только число, которое
показывается рядом.

И это главное, чего проекту не хватало. Замер на 2976 размеченных прогнозах:

    модель   говорит   попадает   разрыв
    own       78.6 %     46.0 %   +32.6 пункта
    llm       60.9 %     47.6 %   +13.3
    fly       10.2 %     46.2 %   −36.0

⚠️ БЕЗ КАЛИБРОВКИ ЭКСПРЕССЫ ПОСЧИТАТЬ НЕЛЬЗЯ В ПРИНЦИПЕ, и это не придирка, а
арифметика. Вероятность прохода экспресса — произведение вероятностей плеч.
Четыре плеча по «0.786» дают 38 % ожидаемых проходов; настоящие 0.46 дают
4.5 %. Ошибка не в полтора раза, а в восемь. Любая попытка «добиться улучшения
удачных экспрессов» на некалиброванных числах меряет собственный самообман.

⚠️ ВЫБРАН ПЛАТТ, А НЕ ИЗОТОНИЧЕСКАЯ РЕГРЕССИЯ, И ЭТО ИЗМЕРЕНО, А НЕ ВЗЯТО ИЗ
КНИЖКИ. Обе проверялись на отложенной по ВРЕМЕНИ трети (учат ранние матчи,
проверяют поздние), рядом с константой — предсказателем, который всегда
называет одно и то же число, выученное на учебной части:

    модель  без калибровки   PAV 5..20 корзин   Платт    константа
    fly           0.3664       0.2432…0.3141    0.2470     0.2473
    llm           0.3388       0.2438…0.2687    0.2438     0.2490
    own           0.4387       0.2879…0.2977    0.2421     0.2470

    (Brier, меньше — лучше)

Изотоническая при широких корзинах иногда выигрывает, при узких проигрывает —
то есть выбор числа корзин решает исход, а данных, чтобы выбрать его честно,
нет. У Платта два параметра, подгонять нечего, и он единственный, кто обошёл
константу у ВСЕХ ТРЁХ моделей.

⚠️ И ВОТ ЧЕСТНЫЙ ВЫВОД, КОТОРЫЙ ВАЖНЕЕ САМОЙ КАЛИБРОВКИ. Выигрыш у константы —
сотые доли: 0.2470 → 0.2421. Наклоны Платта вышли крошечные (a ≈ 0.06…0.12),
а это значит ровно одно: модели почти не несут информации, и калибровка
честно сжимает их к средней. Она убирает ложь, но не создаёт умения.
Дальше нужны не калибровка и не ещё одна модель, а другие признаки и другой
рынок — см. docs/NEXT_SESSION.md.
"""
from __future__ import annotations

import math

# Дальше этих границ логит уходит в бесконечность, а с ним и подгонка.
EPS = 1e-4


def logit(p: float) -> float:
    p = min(max(float(p), EPS), 1.0 - EPS)
    return math.log(p / (1.0 - p))


def sigmoid(x: float) -> float:
    # Разложение по знаку — против переполнения exp на больших |x|.
    if x >= 0:
        return 1.0 / (1.0 + math.exp(-x))
    e = math.exp(x)
    return e / (1.0 + e)


def brier(pairs) -> float:
    """Средний квадрат ошибки вероятности. pairs — [(p, y)], y ∈ {0.0, 1.0}."""
    pairs = list(pairs)
    if not pairs:
        raise ValueError("brier: пустой набор — считать нечего")
    return sum((p - y) ** 2 for p, y in pairs) / len(pairs)


def _log_loss(xs, ts, a: float, b: float) -> float:
    s = 0.0
    for x, t in zip(xs, ts):
        q = min(max(sigmoid(a * x + b), EPS), 1.0 - EPS)
        s -= t * math.log(q) + (1.0 - t) * math.log(1.0 - q)
    return s / len(xs)


def fit_platt(pairs, iters: int = 50, ridge: float = 1e-6) -> tuple[float, float]:
    """Подогнать a, b в sigmoid(a·logit(p) + b) методом Ньютона.

    ⚠️ ЦЕЛИ СГЛАЖЕНЫ ПО ПЛАТТУ: вместо 1 и 0 берутся (N₊+1)/(N₊+2) и
    1/(N₋+2). Без этого на выборке, где какой-то участок уверенности всегда
    угадан, подгонка уезжает в бесконечность — a растёт, пока не упрётся в
    предел точности, и калибровка начинает обещать 0.999.

    ⚠️ ВЫРОЖДЕННЫЙ ВХОД ОТРАБАТЫВАЕТСЯ ОТДЕЛЬНО, И ЭТО НАШЛА ПРОВЕРКА, А НЕ
    ОСТОРОЖНОСТЬ. Если модель называет ОДНУ И ТУ ЖЕ уверенность на всех
    матчах, логит у всех точек один, гессиан вырождается точно (det = 0), и
    Ньютон уезжает в чепуху: на выдуманной выборке «уверен на 0.90, попадает
    в 0.45» калибровка выдала Brier 0.5600 против 0.4580 сырого — то есть
    сделала ХУЖЕ, чем ничего.

    Правильный ответ в этом случае известен заранее: наклона нет, потому что
    различать нечем, и остаётся сдвиг — то есть средняя доля попаданий.
    Так и делается: a = 0, b = logit(доля).
    """
    pairs = [(float(p), float(y)) for p, y in pairs]
    if not pairs:
        raise ValueError("fit_platt: пустой набор")
    n_pos = sum(1 for _, y in pairs if y > 0.5)
    n_neg = len(pairs) - n_pos
    hi = (n_pos + 1.0) / (n_pos + 2.0)
    lo = 1.0 / (n_neg + 2.0)

    xs = [logit(p) for p, _ in pairs]
    ts = [hi if y > 0.5 else lo for _, y in pairs]

    mean_x = sum(xs) / len(xs)
    var_x = sum((x - mean_x) ** 2 for x in xs) / len(xs)
    if var_x < 1e-12:
        return 0.0, logit(sum(ts) / len(ts))

    a, b = 1.0, 0.0
    loss = _log_loss(xs, ts, a, b)
    for _ in range(iters):
        g_a = g_b = h_aa = h_ab = h_bb = 0.0
        for x, t in zip(xs, ts):
            q = sigmoid(a * x + b)
            d = q - t
            w = max(q * (1.0 - q), 1e-12)
            g_a += d * x
            g_b += d
            h_aa += w * x * x
            h_ab += w * x
            h_bb += w
        h_aa += ridge
        h_bb += ridge
        det = h_aa * h_bb - h_ab * h_ab
        if abs(det) < 1e-18:
            break
        step_a = (h_bb * g_a - h_ab * g_b) / det
        step_b = (h_aa * g_b - h_ab * g_a) / det
        # ⚠️ ШАГ С ДРОБЛЕНИЕМ, А НЕ ГОЛЫЙ НЬЮТОН. Полный шаг вблизи плохо
        # обусловленного гессиана перелетает минимум и расходится. Шаг
        # принимается, только если потеря УМЕНЬШИЛАСЬ; иначе делится пополам.
        scale = 1.0
        for _ in range(20):
            na, nb = a - scale * step_a, b - scale * step_b
            nloss = _log_loss(xs, ts, na, nb)
            if nloss <= loss:
                break
            scale /= 2.0
        else:
            break
        moved = abs(scale * step_a) + abs(scale * step_b)
        a, b, loss = na, nb, nloss
        if moved < 1e-10:
            break
    return a, b


def apply_platt(a: float, b: float, p: float) -> float:
    return sigmoid(a * logit(p) + b)


def split_by_order(pairs, train_share: float = 0.7):
    """Разрезать УЖЕ УПОРЯДОЧЕННЫЙ ПО ВРЕМЕНИ список на учёбу и проверку.

    ⚠️ РЕЗАТЬ НАДО ПО ВРЕМЕНИ, А НЕ СЛУЧАЙНО. Случайное разбиение раздаёт
    матчи одного тура в обе половины, и калибровка проверяется на туре, часть
    которого уже видела. Получается завышенная оценка ровно того свойства,
    ради которого всё и затевалось.
    """
    pairs = list(pairs)
    cut = int(len(pairs) * train_share)
    cut = max(1, min(cut, len(pairs) - 1)) if len(pairs) > 1 else len(pairs)
    return pairs[:cut], pairs[cut:]


def evaluate(pairs, train_share: float = 0.7) -> dict:
    """Подогнать на ранней части, измерить на поздней, сравнить с константой.

    Возвращает и параметры, и три числа Brier — чтобы в базе лежало не
    «откалибровано», а на сколько именно это лучше ничего не делать.
    """
    pairs = list(pairs)
    if len(pairs) < 40:
        raise ValueError(f"evaluate: слишком мало размеченного ({len(pairs)})")
    train, test = split_by_order(pairs, train_share)
    a, b = fit_platt(train)
    const = sum(y for _, y in train) / len(train)
    return {
        "a": a,
        "b": b,
        "trained_on": len(train),
        "tested_on": len(test),
        "brier_raw": brier(test),
        "brier_cal": brier([(apply_platt(a, b, p), y) for p, y in test]),
        "brier_const": brier([(const, y) for _, y in test]),
        "const": const,
    }
