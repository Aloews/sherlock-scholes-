"""Легенда не играет в «PSM Makassar»: признак чужой привязки Soccer Wiki.

⚠️ ЭТО ПРО ОШИБКУ, КОТОРУЮ ВИДЕЛ ИГРОК. На экране карточки стоит текущий клуб,
и у легенд он был чужой (замер на боевой базе 15.09.2026):

    Тьерри Анри     известность 100 → São Paulo FC      (закончил в 2014)
    Фернандо Торрес  97             → Patriotas Boyacá   (закончил в 2019)
    Серхио Агуэро    96             → PSM Makassar       (закончил в 2021)
    Патрик Виейра    96             → Betim Futebol      (закончил в 2011)

Soccer Wiki — справочник ДЕЙСТВУЮЩИХ игроков, поэтому у карточки завершившего
карьеру привязки быть не должно вовсе. Но по имени она находится: в честь Анри
называют детей, и «Thierry Henry» 19 лет в «Сан-Паулу» существует на самом деле.

⚠️ ОДНОГО НИЗКОГО РЕЙТИНГА МАЛО, И ЭТО ИЗМЕРЕНО. Средний рейтинг привязки у
карточек с известностью 90+ — 89.2, но при известности ниже сорока у 425
карточек он ниже 80, и там это норма. Порог по рейтингу в одиночку резал бы
живых игроков.

Поэтому признаков ПЯТЬ, и нужны ВСЕ. Каждый по отдельности встречается у
настоящих привязок; вместе они означают «источник считает игрока действующим, а
никаких других следов его игры у нас нет»:

  * известность 90+ — карточка про знаменитость, а не про тёзку;
  * рейтинг ниже 80 — заметно ниже нормы для этой полки;
  * даты рождения нет ни у строки, ни у карточки — сверить людей нечем;
  * нет заявки Transfermarkt — второй источник игрока действующим НЕ считает;
  * нет ни одной строки статистики — sports.ru и ESPN его матчей не видели.

Отрицательные примеры, на которых правило обязано молчать, — в тестах: Ламин
Ямаль и Эндрик знамениты и юны, но у них есть и заявка, и статистика; Ёитиро
Какитани и Энди Кэрролл немолоды и невысоко оценены, но играют по-настоящему.
"""
from __future__ import annotations

FAME_FLOOR = 90
RATING_CEILING = 80


def legend_link_is_suspect(card: dict, link: dict) -> bool:
    """Похожа ли привязка Soccer Wiki на однофамильца знаменитой карточки.

    `card`: fame, born_on, roster_rows, stat_rows.
    `link`: rating, born_on.

    Истина — это ПОДОЗРЕНИЕ, а не приговор: снимать связь по нему можно только
    глазами. Ровно так из шести пойманных карточек двое (Какитани, Кэрролл)
    оказались живыми игроками, и их привязки остались на месте.
    """
    if (card.get("fame") or 0) < FAME_FLOOR:
        return False
    rating = link.get("rating")
    if rating is None or rating >= RATING_CEILING:
        return False
    # Дата есть хоть у одной стороны — людей можно сверить, догадка не нужна.
    if link.get("born_on") or card.get("born_on"):
        return False
    # Второй источник или собственная статистика — след настоящей игры.
    if (card.get("roster_rows") or 0) > 0 or (card.get("stat_rows") or 0) > 0:
        return False
    return True
