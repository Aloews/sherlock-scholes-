-- ============================================================
-- SHERLOCK SCHOLES — test: digest_topics() не склеивает разные сюжеты
--
-- ЧТО ЭТОТ ТЕСТ СТЕРЕЖЁТ. Тема собиралась как СВЯЗНАЯ КОМПОНЕНТА, а
-- компонента транзитивна: A связана с B, B с C — и A с C лежат в одной теме,
-- не имея ни одного общего слова. Замер на 738 живых заметках: компонента из
-- 183 штук, 24.8% всех новостей суток, а внутри — шесть разных сюжетов
-- (Суперкубок Англии, «Зенит» — «Родина», тур ЮФЛ-2, переход Родри, аренда
-- Викарио, сделка «Челси»). Тема получала имя ОДНОГО сюжета и число изданий
-- ВСЕГО кома, то есть верхняя строка экрана прямо утверждала неправду.
--
-- ⚠️ ЭТО ТЕСТ-ГРАНИЦА, А НЕ ТЕСТ-РАВЕНСТВО, и это осознанно.
-- `digest_topics` читает живую `news_items`, и фикстуру сюда не подложить:
-- кластеризация глобальна, она видит ВСЕ заметки окна, а не только мои. Точное
-- утверждение («крупнейшая тема ровно N») ломалось бы каждые двадцать минут от
-- прихода новостей и не значило бы ничего. Поэтому проверяются два СВОЙСТВА,
-- каждое из которых нарушалось прежней реализацией и каждое с большим запасом
-- выполняется нынешней:
--
--   A. ни одна тема не съедает четверть суток   (было 24.8%, стало 6%)
--   B. склейка через алфавиты жива              (её ломали три из трёх
--                                                отвергнутых вариантов)
--
-- Свойство B здесь не для полноты. Все три очевидных лечения кома — порог
-- ребра 4, отсев частых слов по языку, требование «не только клубы» — ком
-- действительно разбирали и ровно так же убивали межъязыковые связи, потому
-- что те держатся на именах клубов. Тест, стерегущий только A, зелёно принял
-- бы любое из них.
--
-- HOW TO RUN — Supabase SQL Editor, или:
--     psql "$DATABASE_URL" -f supabase/tests/digest_topics_clusters.test.sql
--
-- SAFETY. Ничего не пишет, только читает. Транзакция и ROLLBACK — для
-- единообразия с остальными тестами.
--
-- ⚠️ ЕСЛИ ЛЕНТЫ МОЛЧАТ, проверять нечего: на пустом окне обе проверки
-- бессмысленны, и тест это говорит вслух вместо того, чтобы притвориться
-- пройденным.
--
-- Requires: digest_topics.sql, football_digest.sql, digest_football_only.sql.
-- On success prints: `digest_topics: all assertions passed`.
-- ============================================================

BEGIN;

DO $test$
DECLARE
  v_notes      INT;
  v_biggest    INT;
  v_share      NUMERIC;
  v_mixed      INT;
BEGIN
  SELECT count(*) INTO v_notes
  FROM public.news_items n
  WHERE n.published_at > now() - interval '24 hours'
    AND NOT public.non_football_url(n.url);

  IF v_notes < 50 THEN
    RAISE NOTICE 'digest_topics: в окне % заметок — проверять нечего, тест пропущен', v_notes;
    RETURN;
  END IF;

  -- ── A. Ни одна тема не съедает четверть суток ──────────────────────────
  --
  -- Порог 20% выбран не «на глаз»: прежняя реализация давала 24.8% и упала бы,
  -- нынешняя даёт 6% и проходит вчетверо с запасом. Между этими числами нет
  -- ничего, что стоило бы пропустить.
  SELECT max(headlines) INTO v_biggest
  FROM public.digest_topics('ru', 50, 24);

  v_share := round(100.0 * v_biggest / v_notes, 1);
  ASSERT v_share <= 20.0,
    format('A: крупнейшая тема держит %s%% суток (%s из %s заметок) — похоже, '
           'вернулась транзитивная склейка', v_share, v_biggest, v_notes);

  -- ── B. Склейка через алфавиты жива ─────────────────────────────────────
  --
  -- Тема, в которой есть и русская заметка, и нелатинская... точнее: и
  -- русская, и любая другая. Ради этого заведена `digest_translit`, и ровно
  -- это ломало каждое отвергнутое лечение кома.
  SELECT count(*) INTO v_mixed
  FROM public.digest_topics('ru', 50, 24) t
  WHERE 'ru' = ANY(t.langs) AND array_length(t.langs, 1) > 1;

  -- Русских лент две из восьми, поэтому смешанных тем в сутках единицы, а не
  -- десятки. Утверждается ФАКТ НАЛИЧИЯ, а не количество: количество зависит от
  -- того, писали ли сегодня об одном и том же по обе стороны алфавита.
  IF (SELECT count(*) FROM public.news_items n
        WHERE n.published_at > now() - interval '24 hours'
          AND n.lang = 'ru' AND NOT public.non_football_url(n.url)) >= 20 THEN
    ASSERT v_mixed >= 1,
      'B: ни одной темы с русским И другим языком — транслитерация перестала '
      'связывать алфавиты, проверь digest_translit и порог ребра';
  END IF;

  RAISE NOTICE 'digest_topics: all assertions passed (тем-гигантов нет: %%%, смешанных тем: %)',
               v_share, v_mixed;
END
$test$;

ROLLBACK;
