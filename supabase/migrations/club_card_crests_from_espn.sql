-- ===========================================================================
-- sync_club_card_crests — эмблема с ESPN уезжает из справочника в КАРТОЧКУ.
--
-- Владелец прислал скриншот коллекции: карточка «Зенит» с диаграммой
-- астрономического зенита. И сказал: «эмблемы клубов бери с ESPN и его сделай
-- основным».
--
-- ⚠️ ДАННЫЕ БЫЛИ НА МЕСТЕ, ИСПОРЧЕНА ИМЕННО КАРТОЧКА. В справочнике у «Зенита»
-- уже лежит верный герб с ESPN (`.../soccer/500/2533.png`), а в карточке —
-- `Equinox-NO-Zenit-Nadir.jpg`. Это не пробел в сборе, а два хранилища одного
-- факта, разошедшиеся молча. Замер 03.09.2026:
--
--     карточек клубов, связанных со справочником   430
--     из них с гербом ESPN в справочнике           291
--     из них с гербом ESPN в карточке                0   ← ни одной
--     карточек вообще без картинки                 132
--
-- Что лежало в этих 291 карточках вместо герба (смотрено глазами, не по
-- проценту): «Арсенал» — трибуна «Эмирейтс», «Челси» — Стэмфорд Бридж,
-- «Реал» — фасад стадиона, «Кристал Пэлас» — Селхерст Парк, «ПСЖ» — кадр с
-- матча в Киеве, «Ростов» — кадр с «Баварией», «Астана» — фотография города,
-- «Брест» — улица. Однословное имя клуба в вики почти всегда занято не клубом,
-- и P31-гард появился позже, чем записаны эти строки.
--
-- ⚠️ ПОЧЕМУ СВЯЗЬ ПО card_id, А НЕ ПО ИМЕНИ. У `football_club` есть прямая
-- ссылка на карточку. Сопоставление по `club_match_key` здесь и медленнее
-- (430 × 1521 вычислений ключа не уложились в минуту), и врёт молча — ровно
-- тем классом ошибки, из-за которого «Барселона» однажды уехала на
-- многоспортивный клуб.
--
-- ⚠️ ТОЛЬКО ESPN И ТОЛЬКО ПРИ РАСХОЖДЕНИИ. Герб из Викимедиа обратно в
-- карточку не переносится: он и так пришёл ИЗ карточки (`rebuild_football_clubs`
-- копирует `cards.photo_url` в `crest_url`), и перенос был бы пустым кругом.
-- Повторный прогон — no-op, поэтому шаг безопасен для ночного workflow.
--
-- ⚠️ ЭТО ЖЕ ЗАКРЕПЛЯЕТ ГЕРБ В СПРАВОЧНИКЕ. `rebuild_football_clubs` берёт
-- `crest_url = coalesce(excluded.crest_url, ...)`, где `excluded.crest_url` —
-- это `cards.photo_url`. То есть НЕПУСТОЕ фото карточки затирает герб ESPN в
-- справочнике. Замер: 190 верных гербов ESPN стояли в одном ночном прогоне от
-- замены на фотографию стадиона. После этой синхронизации оба хранилища несут
-- одно значение, и прогон становится неподвижной точкой, а не порчей.
--
-- Ночная сборка фотографий трогает только карточки с `photo_url IS NULL`
-- (`run.py --cards-photos`), поэтому записанный герб она уже не перезапишет.
--
-- Возвращает число реально изменённых карточек: «прогон прошёл» без числа
-- ничего не значит.
--
-- Гранты перечислены явно: политика без гранта роняла этот проект дважды.
-- Только service_role: это запись в колоду, игроку она не нужна.
-- ===========================================================================
create or replace function public.sync_club_card_crests()
returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_count integer;
begin
  update cards c
     set photo_url = f.crest_url
    from football_club f
   where f.card_id = c.id
     and f.kind = 'club'
     and c.category = 'club'
     and c.active
     and f.crest_url like '%espncdn%'
     and c.photo_url is distinct from f.crest_url;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke all on function public.sync_club_card_crests() from public, anon, authenticated;
grant execute on function public.sync_club_card_crests() to service_role;
