-- Обучение смотрело на год, а в базе лежит четверть века
-- ======================================================
--
-- Владелец: «выкачай данные за прошлые годы». Качать не пришлось — они уже
-- здесь: в `club_match` 32 285 матчей со счётом, самый ранний 1998 года.
-- Их выбрасывало это представление: `match_date >= current_date - 400`.
--
-- ⚠️ ДВА РАЗНЫХ ОКНА, И ИХ ПУТАЛИ. Одно — окно ПРИЗНАКА: форма команды за
-- 400 суток до матча, оно остаётся прежним, потому что форма пятилетней
-- давности к сегодняшнему матчу отношения не имеет. Второе — окно ВЫБОРКИ:
-- какие матчи вообще становятся строками. Второе было равно первому без
-- причины, и модель училась на одном годе вместо четырёх.
--
-- Замер: 10 546 строк было, 12 543 стало (2023-01-22 … 2026-10-22), плюс
-- 19 %. Прикидка «будет 17 390» была неверна: в ней не учитывались
-- венью-окна (`vh.n >= 4 and va.n >= 4`), которые живое определение требует,
-- а черновой запрос — нет. Здесь записано измеренное число, а не ожидаемое.
--
-- Утечки нет и не появилось: окно признака по-прежнему кончается ЗА СУТКИ до
-- матча, поэтому строка не видит ни себя, ни одноклубников того же дня.
--
-- ⚠️ ПРАВКА СДЕЛАНА ПОДСТАНОВКОЙ В ОПРЕДЕЛЕНИЕ ИЗ САМОЙ БАЗЫ, А НЕ
-- ПЕРЕПЕЧАТКОЙ, И ЭТО ВАЖНО. Файл `duel_features.sql` в репозитории отстал от
-- прода на несколько правок: в нём нет ни `home_key`, ни `outcome`, ни
-- венью-признаков, которыми пайплайн живёт, и объект давно не представление,
-- а МАТЕРИАЛИЗОВАННОЕ представление. Пересоздание «по файлу» снесло бы
-- половину колонок. Поэтому определение читается через `pg_get_viewdef`,
-- меняется одно число, всё остальное переносится байт в байт.
--
-- ⚠️ ПОСЛЕ ЭТОЙ ПРАВКИ ПАРАМЕТРЫ МОДЕЛЕЙ УСТАРЕЛИ: границы train/val/test
-- сдвинулись, значит λ и пороги подобраны на другой выборке. Ночной
-- `step_train` переобучит сам; до первого прогона точность на экране — от
-- прежней подгонки.
--
-- 1500 суток, а не «всё»: дальше в `club_match` начинаются разрозненные
-- кубковые матчи девяностых без соседей по сезону — порог `n >= 10` их и так
-- не пропустит, а сканировать каждую ночь незачем.
do $$
declare
  def text;
  было int;
  стало int;
begin
  select count(*) into было from public.duel_features;
  select pg_get_viewdef('public.duel_features'::regclass, true) into def;

  if position('(CURRENT_DATE - 400)' in def) = 0 then
    raise exception 'окно выборки уже не 400 суток — определение изменилось, правку надо пересмотреть';
  end if;
  def := replace(def, '(CURRENT_DATE - 400)', '(CURRENT_DATE - 1500)');

  execute 'drop materialized view public.duel_features';
  execute 'create materialized view public.duel_features as ' || def;
  execute 'create unique index duel_features_pk on public.duel_features '
          || '(match_date, home_key, away_key)';
  execute 'revoke all on public.duel_features from public, anon, authenticated';
  execute 'grant select on public.duel_features to service_role';

  select count(*) into стало from public.duel_features;
  -- Проверка, а не надежда: если строк не прибавилось, правка не сработала,
  -- и молча оставить её значит потом искать, почему обучение не улучшилось.
  if стало <= было then
    raise exception 'строк не прибавилось: было %, стало % — окно не расширилось', было, стало;
  end if;
  raise notice 'строк признаков: % -> %', было, стало;
end $$;

comment on materialized view public.duel_features is
  'Признаки матча без утечки. Окно ПРИЗНАКА — 400 суток до матча; окно ВЫБОРКИ — 1500 суток. Разбор в duel_features_wider_sample_window.sql.';
