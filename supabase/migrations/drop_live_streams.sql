-- ============================================================================
-- Раздел «идёт сейчас» снят целиком. Что это было и почему его больше нет.
--
-- Владелец: «если блок с трансляциями матчей на ютуб требует много обращений
-- АПИ, то убери его. И чаще ищи свежие голы из лучших лиг».
--
-- ⚠️ ЧЕСТНЫЙ ОТВЕТ НА ВОПРОС ВЛАДЕЛЬЦА: КВОТЫ БЛОК ЕЛ МАЛО. После починки
-- 13.09.2026 статус спрашивался одним вызовом `videos.list` на прогон — 144
-- единицы в сутки при квоте 10 000, то есть 1.4%. Условие «много обращений
-- API» НЕ ВЫПОЛНЯЛОСЬ, и снимать блок по этой причине было бы неправдой.
--
-- Снят он по другой, и она сильнее. ЗАМЕР: шесть проверенных прогонов подряд,
-- двадцать найденных роликов, ИДУЩИХ СРЕДИ НИХ — НОЛЬ. Все двадцать анонсы.
-- Это не случайность дня: в шапке снятого `live_streams.sql` с самого начала
-- было написано, что верхнего дивизиона там почти не будет — права проданы
-- эксклюзивно по странам, и открывают резервные лиги, молодёжь, женский
-- футбол. То есть раздел устроен так, что пуст почти всегда, и всё, что он
-- реально приносил читателю за сутки наблюдений, — ноль.
--
-- Цена при этом не только в квоте: шестнадцать страниц канала каждые десять
-- минут — 2304 обращения к youtube.com в сутки, разбор недокументированной
-- разметки и ЕЩЁ ОДИН источник, который может сломаться молча. За ноль строк.
--
-- ⚠️ ОСВОБОДИВШЕЕСЯ ОТДАНО ТУДА, КУДА ПРОСИЛ ВЛАДЕЛЕЦ. Шесть каналов лучших
-- лиг (АПЛ, Ла Лига, Серия А, Бундеслига, Лига 1, УЕФА) переведены в
-- `poll_group = 0` — опрос каждые десять минут вместо раза в час, то есть
-- ВШЕСТЕРО чаще. Арифметика по факту таблицы:
--
--   было:  78 каналов × 2 единицы × 24 прогона  = 3744 (37%) + 144 эфиры
--   стало: 72 × 2 × 24 + 6 × 2 × 144            = 5184 (52%)
--
-- Половина квоты по-прежнему свободна.
--
-- ⚠️ САМА EDGE-ФУНКЦИЯ `live-streams` ОСТАЁТСЯ ВЫЛОЖЕННОЙ, И ЭТО НЕ ЗАБЫТО:
-- удалять функции Supabase умеет только панель, из SQL этого не сделать. Звать
-- её больше некому — расписание снято первой же строкой выше, а исходник из
-- репозитория удалён. Снесите её в панели, когда будете рядом; до тех пор она
-- просто лежит и ничего не делает.
--
-- ⚠️ ВЕРНУТЬ ЭТО НЕ «ОТКАТИТЬ КОММИТ». Вместе с блоком снята таблица, четыре
-- функции, расписание и Edge-функция `live-streams`; каналы вида 'live'
-- удалены из `digest_source`. Если раздел понадобится снова — заводите его
-- заново и с ответом на вопрос, которого у прежнего не было: чем он
-- оправдывает свои 2304 запроса в сутки.
-- ============================================================================

select cron.unschedule('fetch-live-streams')
 where exists (select 1 from cron.job where jobname = 'fetch-live-streams');

drop function if exists public.fetch_live_streams();
drop function if exists public.digest_live_matches(integer);
drop function if exists public.digest_upcoming_matches(integer, integer);
drop function if exists public.prune_live_streams();
-- Предикаты «это матч» / «это студия» читались ТОЛЬКО отсюда: проверено
-- обходом миграций, экранов и скриптов. Без эфиров они не читаются ниоткуда.
drop function if exists public.looks_like_match(text);
drop function if exists public.is_studio_talk(text);
drop table if exists public.live_streams;

-- Каналы, заведённые ТОЛЬКО ради эфиров (Concacaf, A-Leagues, AFC Asian Cup).
-- В ленту голов они не шли — это и был смысл отдельного вида, — значит без
-- эфиров им делать нечего.
delete from public.digest_source where kind = 'live';

-- ---------------------------------------------------------------------------
-- Лучшие лиги — каждые десять минут.
--
-- ⚠️ ОДИН UPDATE, А НЕ ПРАВКА ФУНКЦИИ, И ЭТО НАМЕРЕННО. Список источников
-- живёт в таблице ровно затем, чтобы такие вещи не стоили деплоя: `poll_group
-- = 0` уже значит «каждый прогон», и `rotate_digest_poll_group` это умеет с
-- самого начала.
--
-- ⚠️ ЛИГИ, А НЕ КЛУБЫ, и это решение, а не экономия. Гол лиги выкладывает
-- сама лига; клубный канал выкладывает обзор своего матча, и обычно позже.
-- Поднять вдобавок дюжину больших клубов можно — это ещё 2880 единиц, 81%
-- квоты, — но выигрыш там меньше, а запас нужен живой: квота общая с
-- `player-stats` и с любым будущим шагом.
-- ---------------------------------------------------------------------------
update public.digest_source
   set poll_group = 0
 where kind = 'channel' and wanted
   and name in ('Premier League', 'LALIGA', 'Serie A', 'Bundesliga', 'Ligue 1', 'UEFA');
