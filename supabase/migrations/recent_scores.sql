-- ============================================================================
-- Счета для истории матчей — независимо от того, ждёт ли их прогноз.
--
-- ЖАЛОБА, С КОТОРОЙ НАЧАЛОСЬ: «результаты вчерашних матчей до сих пор не
-- доехали». Причина — не поломка, а сама политика `sports_awaiting_scores()`
-- (match_predictions.sql): счета спрашиваются ТОЛЬКО у турниров, где есть
-- незакрытый прогноз на завершившийся матч. Замер на боевой базе 24.08.2026:
-- активных прогнозов — 0 (последний, от 12.08, уже вышел за семидневный пол
-- той функции и никогда не будет закрыт), поэтому 15 из 48 матчей вчерашнего
-- дня так и остались без счёта спустя 11–20 часов после финального свистка —
-- не потому что провайдер их не знает, а потому что мы ни разу не спросили.
--
-- Это разумная политика для прогнозов (см. заголовок match_predictions.sql —
-- бюджет платит за игроков, а не за календарь), но игрок листает историю
-- матчей независимо от того, ставил ли он прогноз, и пустой счёт там читается
-- как «результаты ещё не пришли», а не как «мы решили не спрашивать».
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ РАСШИРЕНИЕ sports_awaiting_scores(). У них
-- разное окно и разная причина существования: там семь дней, потому что чей-то
-- счёт в фэнтези-смысле обязан рано или поздно закрыться; здесь двое суток,
-- потому что цель — свежесть календаря, а не гарантия ответа. Общее имя на
-- двоих было бы неверным для обоих читателей — тот же принцип, что развёл
-- current_week_start() и current_play_date() (player_streak.sql).
--
-- ⚠️ ВЫЗЫВАЕТСЯ РЕЖЕ, ЧЕМ ПРОГНОЗНЫЙ ПУТЬ, И ЭТО НЕ СЛУЧАЙНОСТЬ. Двадцать
-- турниров каждый день — 600 кредитов в месяц против потолка в 500 (см.
-- шапку functions/football-fixtures/index.ts — тот же расчёт уже был сделан
-- один раз и отверг «спрашивать все двадцать ежедневно»). Эта функция сама
-- по себе бюджет не бережёт — его бережёт РАСПИСАНИЕ (schedule_fetch_scores.sql,
-- отдельное задание раз в сутки, а не каждые шесть часов, как у прогнозов).
-- ============================================================================

create or replace function public.sports_needing_recent_scores()
returns table (sport_key text)
language sql stable
security definer
set search_path = public
as $$
  select distinct f.sport_key
    from fixtures f
   where f.commence_at < now() - interval '105 minutes'
     and f.commence_at > now() - interval '48 hours'
     and not f.completed;
$$;

revoke all on function public.sports_needing_recent_scores() from public;
grant execute on function public.sports_needing_recent_scores() to service_role;

comment on function public.sports_needing_recent_scores() is
  'Турниры с матчем, который начался 105 минут – 48 часов назад и всё ещё не '
  'отмечен completed. Не про прогнозы — про свежесть календаря/истории; вызывается '
  'раз в сутки отдельным заданием (schedule_fetch_scores.sql), не каждые 6 часов.';
