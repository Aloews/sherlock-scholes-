-- Видео из ВК: две группы владельца
-- =================================
--
-- ЗАЧЕМ. Русские обзоры у нас брались с ОДНОГО источника — канала РПЛ на
-- Rutube, — и он уже подвёл: замер 20.09.2026 показал, что первая страница
-- его выдачи замерла на 11 сентября, пока лига играла 12 матчей 12–17-го.
-- Страницы выдачи закрыты robots.txt Rutube дважды (`*page=*` и `*?`), то
-- есть обойти нечем. Вторая точка входа снимает единственную точку отказа.
--
-- ⚠️ ТОЛЬКО API, HTML НЕ ВАРИАНТ, И ЭТО ПРОВЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО:
--
--     GET https://vkvideo.ru/@pl_forever        -> 302 login.vk.ru/?act=autologin
--     GET https://vkvideo.ru/@sportcast.online  -> 302 login.vk.ru/?act=autologin
--     GET https://api.vk.com/method/utils.resolveScreenName?screen_name=pl_forever
--                                               -> error_code 15, "token required"
--
-- При этом `robots.txt` ВК в секции `User-agent: *` прямо РАЗРЕШАЕТ
-- `/video-*` и `/video*_*`. То есть ссылка на сам ролик законна; закрыт
-- обход страницы сообщества, а не просмотр.
--
-- =====================================================================
-- ГДЕ ВЗЯТЬ КЛЮЧ И КУДА ЕГО ПОЛОЖИТЬ
-- =====================================================================
--
-- 1. Завести приложение: https://dev.vk.com/ -> «Мои приложения» ->
--    «Создать приложение» -> тип «Standalone-приложение». Ничего публиковать
--    и проходить модерацию не нужно: ключ выдаётся сразу.
--
-- 2. В приложении: «Настройки» -> «Сервисный ключ доступа». Это длинная
--    строка из шестнадцатеричных знаков. Она НЕ привязана к вашему личному
--    аккаунту и не даёт доступа к переписке — только к публичным данным.
--
-- 3. Положить её в секреты Edge-функций Supabase под именем
--    `VK_SERVICE_TOKEN`:
--
--      Dashboard -> Project Settings -> Edge Functions -> Secrets -> Add new
--      имя:     VK_SERVICE_TOKEN
--      значение: <сервисный ключ>
--
--    Или одной командой, если под рукой CLI:
--
--      supabase secrets set VK_SERVICE_TOKEN=<ключ>
--
-- 4. Больше никуда её класть НЕ НАДО. Во фронтенд — тем более: всё, что с
--    префиксом `VITE_`, уезжает в браузер читателя.
--
-- ⚠️ ЕСЛИ СЕРВИСНОГО КЛЮЧА ОКАЖЕТСЯ МАЛО. У ВК часть методов закрыта для
-- сервисного ключа и требует пользовательского. Проверяется по отчёту
-- функции: строка `vk_silent` с обеими группами при `vk_configured: true`
-- и запись в логах вида `vk video.get 15 ...` означает именно это, а не
-- пустые группы. Лечится ключом, полученным через Implicit Flow на свой же
-- аккаунт (права `video,offline`), и кладётся он под тем же именем.
--
-- Отчёт различает три состояния намеренно: «ключа нет»
-- (`vk_configured: false`), «ключ есть, группы молчат» (`vk_silent` не пуст)
-- и «всё в порядке». Один общий ноль на все случаи уже стоил этому проекту
-- пяти суток слепоты в сборе ESPN.

