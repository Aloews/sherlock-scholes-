-- ---------------------------------------------------------------------------
-- Учащение до каждых двадцати минут.
--
-- ЗАЧЕМ. Голы обновлялись редко не потому, что источник медленный, а потому
-- что прогон был раз в час на пять европейских каналов. Летом Европа не
-- играет, и лента вырождалась: за 6 августа — шесть роликов с трёх каналов.
--
-- ЧТО ПРИ ЭТОМ НЕ УЧАЩАЕТСЯ. Atom-фид YouTube закрыт его же robots.txt
-- (`Disallow: /feeds/videos.xml`), поэтому сама функция берёт ролики этим
-- путём по-прежнему раз в час — она смотрит на минуту прогона. Втрое чаще
-- ходят только RSS-ленты изданий, которые это разрешают, а все каналы каждый
-- прогон опрашиваются лишь при заданном YOUTUBE_API_KEY, то есть по
-- официальному API.
-- ---------------------------------------------------------------------------
-- ---------------------------------------------------------------------------
-- Учащение до каждых десяти минут.
--
-- ЗАЧЕМ. Двадцать минут — это до двадцати минут задержки на новости и на
-- ролики лиг, которые играют, когда Европа спит. Квота позволяет вдвое чаще
-- с большим запасом, так что платить за свежесть нечем.
--
-- КВОТА, СЧИТАННАЯ ПО КОДУ, А НЕ НА ГЛАЗ. `fetchClipsViaApi` делает ДВА
-- запроса на канал: `playlistItems` (1 единица) и `videos.list?part=statistics`
-- (ещё 1, и он обязателен — плейлист не отдаёт просмотров). Каналов девять, и
-- при заданном ключе через API идут ВСЕ ДЕВЯТЬ, а не только те, у кого
-- `needs_key`: в index.ts стоит `if (YT_KEY) return fetchClipsViaApi(...)`
-- раньше проверки способа. Итого 18 единиц за прогон:
--
--   */20   72 прогона в сутки   1296 единиц   13% от 10 000
--   */10  144 прогона           2592          26%
--   */5   288 прогонов          5184          52%
--
-- Взято */10. RSS-ленты изданий чаще десяти минут всё равно не обновляются, а
-- половину суточной квоты за это отдавать незачем.
--
-- ⚠️ ЭТО РАСПИСАНИЕ СВЯЗАНО С ОДНОЙ СТРОКОЙ В index.ts, и связь неочевидна.
-- Без ключа ролики берутся Atom-путём, закрытым в robots.txt, и потому ровно
-- раз в час — гейтом `new Date().getUTCMinutes() < 20`. Гейт написан под
-- ПРЕЖНИЙ период: при `*/20` он истинен только в :00, а при `*/10` станет
-- истинен и в :00, и в :10, то есть удвоит хождение по закрытому пути.
--
-- Сейчас это спит: ключ задан, и Atom-ветка не исполняется вовсе. Но если
-- YOUTUBE_API_KEY когда-нибудь снимут, гейт в index.ts обязан стать
-- `< 10` — иначе учащение расписания молча превратится в удвоение обхода
-- запрета, и никакой отчёт этого не покажет.
-- ---------------------------------------------------------------------------
select cron.schedule(
  'fetch-football-digest',
  '*/10 * * * *',
  $$select public.fetch_football_digest()$$
);
