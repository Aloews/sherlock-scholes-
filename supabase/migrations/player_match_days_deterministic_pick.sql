-- `player_match_days` выбирал произвольную строку из двух
-- =======================================================
--
-- ⚠️ `DISTINCT ON` С НЕПОЛНЫМ ТАЙ-БРЕЙКОМ ОТДАЁТ РАЗНЫЕ ОТВЕТЫ НА ОДНИ И ТЕ
-- ЖЕ ДАННЫЕ. Порядок был `card_id, match_date, (minutes is not null) desc,
-- source`, и когда у карточки два матча в один день ИЗ ОДНОГО источника,
-- победителя выбирал план запроса, а не правило.
--
-- Нашлось при сверке кэша рейтинга с живым расчётом: четыре карточки
-- разошлись, ярче всех Rafinha — 6 голов живьём против 3 в кэше при
-- одинаковом числе матчей. Один и тот же запрос дважды подряд отвечает
-- одинаково (план тот же), а два РАЗНЫХ запроса над тем же представлением —
-- уже нет.
--
-- ⚠️ ЭТО НЕ ЛЕЧИТ ПРИЧИНУ, И ЛЕЧИТЬ ЕЁ ЗДЕСЬ НЕЛЬЗЯ. Два матча у одной
-- карточки в один день — это дубль карточки или неверная привязка имени;
-- сборщик о них кричит («collapsed 14 duplicate keys», в примерах два
-- РАЗНЫХ матча казахской лиги на одну карточку в один день). Дубли — это
-- отдельная работа по данным, она записана в docs/NEXT_SESSION.md. Здесь
-- чинится только то, что выбор обязан быть ОДИНАКОВЫМ при каждом чтении:
-- иначе одно и то же место экрана показывает то шесть голов, то три, и ни
-- одно из чисел нельзя ни воспроизвести, ни проверить.
--
-- Тай-брейк дописан до полного: после источника — турнир, команды и сами
-- числа. Любые две строки группы теперь упорядочены строго.
--
-- Сверка после починки: кэш минус живой расчёт — ноль, живой минус кэш —
-- ноль, на 1061 строке и четырёх колонках.
create or replace view public.player_match_days as
  select distinct on (card_id, match_date)
         card_id, match_date, tournament, home_team, away_team,
         home_score, away_score, minutes, goals, assists, yellow, red, source
    from player_match_stats s
   where not disputed
   order by card_id, match_date,
            (minutes is not null) desc,
            source,
            tournament, home_team, away_team,
            goals desc, assists desc;
