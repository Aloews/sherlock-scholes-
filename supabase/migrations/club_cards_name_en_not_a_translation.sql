-- name_en клуба — это ЕГО АНГЛИЙСКОЕ ИМЯ, а не перевод русского слова.
--
-- ⚠️ НАЙДЕНО НЕ ГЛАЗАМИ, А ПОСЛЕ ЗАПУСКА rebuild_football_clubs. До прогона
-- дублей в справочнике не было; после — «Зенит» и «Факел» стали двумя клубами
-- каждый. Причина в самой сборке:
--
--     club_key = club_norm_key(coalesce(c.name_en, c.name))
--
-- У «Зенита» в карточке стояло name_en «Zenith», у «Факела» — «Torch». Это
-- перевод слова, а не имя клуба: зенит — точка небесной сферы, факел — палка с
-- огнём. Ключ выходил `zenith` и `torch`, в справочнике заводилась ВТОРАЯ
-- строка того же клуба, и на экране «команды и статистика» клуб двоился: одна
-- строка с 26 матчами и составом, вторая пустая.
--
-- Тот же перевод объясняет и картинку: резолв статьи по «Zenith» приводил к
-- астрономическому зениту, и в карточку попадала диаграмма «Equinox-NO-Zenit-
-- Nadir.jpg» — тот самый скриншот, который прислал владелец.
--
-- ⚠️ ВИНОВАТОСТЬ ДОКАЗАНА РЕЗОЛВЕРОМ, А НЕ ОТСУТСТВИЕМ ДАННЫХ. Пустых ключей,
-- собранных из name_en, в справочнике 86, но пустота сама по себе не улика:
-- у безвестного клуба матчей нет по той же причине, и первая версия ревизии
-- клубных фото ровно так оболгала «Амкар», «Волеренгу» и «Кайзерслаутерн».
-- Поэтому здесь виновными признаны только те, у кого `resolve_club_key` по
-- РУССКОМУ имени (псевдонимы построены из матчей) указывает на другой ключ, и
-- у того ключа данные есть:
--
--     Факел  torch  → fakel voronezh       26 матчей, состав 10
--     Зенит  zenith → zenit st petersburg  26 матчей, состав 21
--
-- Таких ровно два. «Арминия» (name_en «Arminius», фото памятника вождю
-- херусков) под правило НЕ попала: резолвер её не знает, доказательства нет —
-- значит не трогаем. Гипотеза без улики карточку не меняет.
--
-- ⚠️ ИМЯ ПОДОБРАНО ТАК, ЧТОБЫ КЛЮЧ СОШЁЛСЯ С СУЩЕСТВУЮЩИМ. Проверено
-- вычислением, а не на глаз: `club_norm_key('FC Zenit St Petersburg')` даёт
-- `zenit st petersburg`, а `'FC Zenit Saint Petersburg'` — `zenit saint
-- petersburg`, то есть ТРЕТИЙ клуб. Ошибка в написании города завела бы новый
-- дубль вместо починки старого.
-- ===========================================================================
update cards set name_en = 'FC Zenit St Petersburg'
 where category = 'club' and name = 'Зенит' and name_en = 'Zenith';

update cards set name_en = 'FC Fakel Voronezh'
 where category = 'club' and name = 'Факел' and name_en = 'Torch';

-- То же самое в справочнике: строка живёт своей копией имени, и до следующей
-- ночной пересборки экран показывал бы старое.
update football_club set name_en = 'FC Zenit St Petersburg'
 where club_key = 'zenit st petersburg';

update football_club set name_en = 'FC Fakel Voronezh'
 where club_key = 'fakel voronezh';

-- Пустые двойники. Условия — не для красоты: они не дают удалить строку, если
-- к ней успели привязаться данные. Ключ, за которым стоит хоть один матч,
-- состав или псевдоним, останется на месте, и удаление просто ничего не тронет.
delete from football_club f
 where f.club_key in ('zenith', 'torch')
   and not exists (select 1 from club_match m
                    where m.home_key = f.club_key or m.away_key = f.club_key)
   and not exists (select 1 from club_squad s where s.club_key = f.club_key)
   and not exists (select 1 from club_alias a where a.club_key = f.club_key)
   and not exists (select 1 from club_name_seen n where n.club_key = f.club_key);
