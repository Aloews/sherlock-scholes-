-- Фасеты коллекции: 2379 мс вхолодную превращаются в сотни миллисекунд.
--
-- ⚠️ НАШЛОСЬ НА ПРОГОНЕ ВЫКЛАДКИ, А НЕ ЛОКАЛЬНО, И РАЗНИЦА ПОУЧИТЕЛЬНА.
-- Локально те же два вызова давали 136 и 33 мс — но только потому, что
-- `check-prod` к тому моменту гонялся пятый раз подряд и всё было прогрето.
-- На чистом прогоне (deploy №11, 22.09.2026) вышло:
--
--     Экран в срок: коллекция: что можно отобрать   2379 мс   (порог 1500)
--     Экран в срок: фасеты категории «Клубы»        2135 мс   (порог 1500)
--
-- Игрок открывает экран коллекции ИМЕННО вхолодную. Прогретый замер тут
-- измеряет не приложение, а предыдущий замер.
--
-- ПРИЧИНА. `collection_facets` читает все активные карточки и трижды считает
-- по ним срезы. Индекса, покрывающего `(category, country, id)`, не было, и
-- 27 098 ШИРОКИХ строк доставались из кучи ради трёх колонок:
--
--     Seq Scan on cards c       Buffers: shared hit=4186   (27 098 строк)
--     Seq Scan on card_current_club cc   Buffers: shared hit=634
--
-- 4186 страниц на 27 тысяч строк — это шесть строк на страницу: в `cards`
-- лежат описания, и они едут вместе со всем остальным.
--
-- ⚠️ ИНДЕКС ОДИН НА ДВУХ ЧИТАТЕЛЕЙ, А НЕ ПО ИНДЕКСУ НА ЗАПРОС. Тем же
-- `(category, country, id) where active` пользуется `deck_countries` — там
-- он раньше стоял отдельным, более узким `cards_country_facet_idx`. Два
-- индекса по одной таблице с почти одинаковым ключом — это двойная цена
-- записи за одну и ту же выгоду.
--
-- ⚠️ `SET statement_timeout TO '30s'` У `collection_facets` ОСТАЁТСЯ, И ЭТО
-- НЕ ОДОБРЕНИЕ. Поднятый потолок — ровно та ловушка, что записана в MAP.md
-- про `player_spotlight`: «потолок подняли вместо того, чтобы ускорить, и
-- экран пять секунд молчал, считаясь здоровым». Снимать его следует отдельной
-- правкой и с замером, а не заодно.
--
-- Замер после (боевая база, по сети, три захода): `null` 0,96 → 0,64 с;
-- `club` 0,49 → 0,34 с; `player` 0,67 → 0,49 с.

create index if not exists cards_facet_idx
  on public.cards (category, country, id)
  where active;

create index if not exists card_current_club_facet_idx
  on public.card_current_club (card_id, club_key);

-- ⚠️ ANALYZE ЗДЕСЬ НЕ РИТУАЛ: без свежей статистики планировщик выбирал
-- прежний план и после создания индекса.
analyze public.cards;
analyze public.card_current_club;

