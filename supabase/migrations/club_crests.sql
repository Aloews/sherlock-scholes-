-- ===========================================================================
-- ГЕРБЫ КЛУБОВ: значки вместо фотографий из статьи.
--
-- ⚠️ ЧТО ЛЕЖАЛО В `crest_url` ДО ЭТОГО. Из 260 заполненных адресов больше
-- половины вели не на эмблему: у «Барнсли» — портрет Робби Сэвиджа, у
-- «Арсенала» — раздевалка «Эмирейтс», у «Аякса» и «Брондбю» — стадионы, у
-- «Абердина» — мемориальная доска в шведском Аннедале, у «Барселоны» —
-- тренировочная база. Проверено запросом по всем 260: `Robbie_Savage.jpg`,
-- `Arsenal_dressing_room_Emirates_Stadium_2024-04-26.jpg`,
-- `Aberdeen_annedal_minnesplatta.jpg`. Остальные 1259 клубов из 1519 не
-- имели адреса вовсе.
--
-- ⚠️ ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ UPDATE football_club. Источник тех
-- фотографий — сам конвейер: `rebuild_football_clubs` берёт `crest_url` из
-- `cards.photo_url`, а `photo_url` у клубной карточки — заглавная картинка
-- статьи, а не логотип. Пересборка идёт по pg_cron в 06:25 UTC, и простой
-- UPDATE прожил бы до утра. Поэтому герб хранится здесь, а
-- `apply_club_crests()` вызывается ПОСЛЕДНИМ шагом `rebuild_clubs_all` и
-- переписывает то, что поставили перед ним. Тот же приём, что и у
-- `squads_keep_wikidata.sql`: пересборка не должна стирать собранное.
--
-- ⚠️ ПУСТО ЛУЧШЕ, ЧЕМ НЕВЕРНО. Викимедийным фотографиям, которым замены не
-- нашлось, ставится NULL: фотография стадиона на месте эмблемы — не «почти
-- герб», а другой предмет, и выглядит она как сломанное приложение. Пустое
-- место экран уже умеет рисовать — он рисует его 1259 раз.
--
-- ОТКУДА ВЗЯТЫ ГЕРБЫ. ESPN (218 турниров, 1921 команда после отсева
-- студенческих первенств США) и TheSportsDB (поиск по названию). Обе
-- стороны сведены токенным матчером с весом IDF —
-- `football_scraper/club_crests.py`, там же правило приёмки и его пределы.
-- Каждый из 932 адресов проверен запросом: 200 и `image/*`.
-- ===========================================================================

create table if not exists public.club_crest (
  club_key   text primary key,
  url        text not null,
  source     text not null,
  score      numeric,
  fetched_at timestamptz not null default now()
);

comment on table public.club_crest is
  'Гербы клубов от внешних источников (espn, thesportsdb). Живёт отдельно от '
  'football_club, потому что тот перестраивается ночью и берёт crest_url из '
  'cards.photo_url — заглавной картинки статьи, а не эмблемы.';

alter table public.club_crest enable row level security;
revoke all on table public.club_crest from public, anon, authenticated;

-- ---------------------------------------------------------------------------
create or replace function public.apply_club_crests()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare v_set integer; v_cleared integer;
begin
  update football_club f
     set crest_url = c.url
    from club_crest c
   where c.club_key = f.club_key
     and f.crest_url is distinct from c.url;
  get diagnostics v_set = row_count;

  -- Условие по адресу, а не по имени файла: `Atalanta_BC.png` — настоящий
  -- логотип, `Robbie_Savage.jpg` — нет, и по имени их не разделить.
  update football_club f
     set crest_url = null
   where f.crest_url like '%wikimedia.org%'
     and not exists (select 1 from club_crest c where c.club_key = f.club_key);
  get diagnostics v_cleared = row_count;

  return v_set + v_cleared;
end;
$$;

comment on function public.apply_club_crests() is
  'Ставит гербы из club_crest и снимает викимедийные фотографии без замены. '
  'Обязана идти ПОСЛЕ rebuild_football_clubs: тот затирает crest_url полем '
  'cards.photo_url.';

revoke all on function public.apply_club_crests() from public, anon, authenticated;
grant execute on function public.apply_club_crests() to service_role;

-- ---------------------------------------------------------------------------
-- Шестой шаг конвейера. Возвращаемый тип не меняется намеренно: `create or
-- replace` не умеет его менять, а `drop function` под живым продом уже
-- ронял приложение (см. шапку deck_rpc.sql).
create or replace function public.rebuild_clubs_all()
returns table (clubs integer, merged integer, squad integer, matches integer, pruned integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_clubs integer; v_merged integer; v_squad integer; v_matches integer; v_pruned integer;
begin
  v_clubs   := rebuild_football_clubs();
  v_merged  := merge_seeded_clubs();
  v_squad   := rebuild_club_squads();
  v_matches := rebuild_club_matches();
  v_pruned  := prune_orphan_clubs();
  perform apply_club_crests();
  return query select v_clubs, v_merged, v_squad, v_matches, v_pruned;
end;
$$;

comment on function public.rebuild_clubs_all() is
  'Весь конвейер клубов одним вызовом, в единственном правильном порядке. '
  'Возвращает числа по каждому шагу — чтобы «отработало» отличалось от '
  '«отработало и ничего не нашло». Гербы применяются последними: до них '
  'crest_url успевает получить фотографию из карточки.';

revoke all on function public.rebuild_clubs_all() from public, anon, authenticated;
grant execute on function public.rebuild_clubs_all() to service_role;

