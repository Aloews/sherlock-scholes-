-- Индекс по турниру: «сколько матчей дала лига» перестаёт стоить полтаблицы.
--
-- ⚠️ ПЕРВИЧНЫЙ КЛЮЧ ЭТОТ ВОПРОС НЕ ЗАКРЫВАЕТ, ХОТЯ КОЛОНКИ В НЁМ ЕСТЬ.
-- Ключ — (card_id, match_date, tournament), и ведущая колонка в нём card_id.
-- Запрос без card_id может пройти по такому индексу только целиком, фильтруя
-- каждую запись. Замер на боевой базе (89 714 строк), запрос «матчи Серии Б за
-- 30 суток»:
--
--     Index Only Scan using player_match_stats_pkey   455 мс, 1061 буфер
--     Index Only Scan using ..._tournament_idx          6 мс,    4 буфера
--
-- В семьдесят раз, и это не оптимизация ради красоты: раздел «Охват» в
-- check-prod задаёт этот вопрос по КАЖДОЙ лиге списка — 47 запросов, то есть
-- 21 секунда против трети секунды. У анонима к тому же стоит потолок в 3
-- секунды на запрос: 455 мс укладываются, но запас до отказа был двукратный, а
-- таблица растёт с каждой ночью.
--
-- Порядок колонок именно такой: сначала равенство (tournament), потом
-- диапазон (match_date). Обратный порядок оставил бы турнир фильтром.
--
-- DESC у даты — чтобы тем же индексом брался и «последний матч лиги» без
-- сортировки.
create index if not exists player_match_stats_tournament_idx
  on public.player_match_stats (tournament, match_date desc);

comment on index public.player_match_stats_tournament_idx is
  'Охват по лигам: 455 мс -> 6 мс. Первичный ключ ведёт card_id, и без него '
  'проход по ключу идёт целиком.';
