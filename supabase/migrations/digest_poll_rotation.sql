-- ============================================================================
-- РОТАЦИЯ ОПРОСА КЛУБОВ — ВРЕМЕННЫЙ ШИМ В БАЗЕ.
--
-- ЗАЧЕМ ОН ВООБЩЕ ЕСТЬ. Правильное место для этой логики — сама функция
-- football-digest: она уже умеет poll_group (см. pollGroupNow в index.ts,
-- коммит с 47 клубами). Но выкатить её из этой среды нечем: supabase CLI
-- требует SUPABASE_ACCESS_TOKEN, которого здесь нет, а единственный
-- доступный путь — передать 47 КБ исходника параметром инструмента, то есть
-- ВОСПРОИЗВЕСТИ его целиком по памяти. Для боевой функции это неприемлемо:
-- одна незамеченная подмена символа в разборе RSS ломает прод молча.
--
-- Поэтому ротация делается там, где её можно ПРОВЕРИТЬ запросом, — в базе.
--
-- КАК. Функция читает `digest_source?enabled=is.true`. Значит достаточно,
-- чтобы к моменту прогона в `enabled` стояла ровно нужная группа. Отсюда два
-- столбца вместо одного:
--
--   wanted   — чего хочет владелец: «этот источник нужен». Меняется руками.
--   enabled  — что опрашивается В ЭТОТ ПРОГОН. Меняется роботом, каждые 10 мин.
--
-- ⚠️ Раньше `enabled` значил первое. Теперь — второе, и заметки о выключенных
-- источниках («Вернул НОЛЬ», «отвечает 302») переехали в смысл `wanted`.
-- Выключить источник насовсем теперь = `wanted = false`, а не `enabled`.
--
-- РАСПИСАНИЕ. Дайджест идёт в 0,10,20,30,40,50. Ротация идёт ЗА МИНУТУ до
-- него — в 9,19,29,39,49,59, — и выставляет группу для БЛИЖАЙШЕГО прогона,
-- отсюда `+ 1` в расчёте минуты. Минутный зазор снимает гонку: два задания
-- pg_cron порядка между собой не гарантируют, а разнесённые на минуту — да.
--
-- ⚠️ СОВМЕСТИМОСТЬ С БУДУЩИМ ДЕПЛОЕМ ФУНКЦИИ — ПРОВЕРЕНА, А НЕ ПРЕДПОЛОЖЕНА.
-- Когда функцию наконец выкатят, она начнёт фильтровать по СВОЕЙ формуле
-- floor(minute/10) mod 6 + 1 поверх уже отфильтрованного списка. Формулы
-- совпадают по построению:
--
--   ротация в :09 ставит группу floor((9+1) mod 60 / 10) mod 6 + 1 = 2
--   функция в :10 просит          floor(10/10)        mod 6 + 1 = 2
--   ротация в :59 ставит          floor((59+1) mod 60 / 10) mod 6 + 1 = 1
--   функция в :00 просит          floor(0/10)         mod 6 + 1 = 1
--
-- То есть двойная фильтрация даёт тот же список, и порядок выкатки неважен.
--
-- КАК СНЯТЬ ШИМ, когда функция выкачена (и это НАДО сделать — два механизма
-- на одну задачу однажды разойдутся):
--
--   select cron.unschedule('rotate-digest-poll-group');
--   drop function public.rotate_digest_poll_group();
--   update digest_source set enabled = wanted where kind = 'channel';
--
-- Столбец `wanted` при этом остаётся: он и есть честное «источник нужен».
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Намерение владельца, отдельно от того, что опрашивается сейчас.
-- ---------------------------------------------------------------------------
alter table digest_source
  add column if not exists wanted boolean not null default true;

comment on column digest_source.wanted is
  'Нужен ли источник вообще (решает человек). `enabled` — опрашивается ли он '
  'в ЭТОТ прогон (решает rotate_digest_poll_group). Выключать источник '
  'насовсем нужно через wanted.';

-- Перенос текущего состояния. Клубы сейчас выключены нарочно — они ждали
-- этой миграции, поэтому им wanted = true. Всем остальным wanted = enabled:
-- у выключенных лент и каналов в note написано, ПОЧЕМУ они выключены.
update digest_source
   set wanted = case when kind = 'channel' and poll_group between 1 and 6
                     then true else enabled end;

-- ---------------------------------------------------------------------------
-- Кто опрашивается в ближайший прогон.
-- ---------------------------------------------------------------------------
create or replace function public.rotate_digest_poll_group()
returns void language plpgsql security definer set search_path = public as $$
declare
  g int;
begin
  -- Группа для БЛИЖАЙШЕГО прогона, а не для текущей минуты: задание стоит
  -- за минуту до дайджеста, поэтому берётся minute + 1.
  -- Целочисленно от начала до конца: floor() отдаёт double precision, а
  -- оператор % его не принимает. Деление int/int в Postgres и так усекает.
  g := ((((extract(minute from now())::int + 1) % 60) / 10) % 6) + 1;

  update digest_source
     set enabled = wanted and (poll_group = 0 or poll_group = g)
   where kind = 'channel';
end;
$$;

comment on function public.rotate_digest_poll_group() is
  'Временный шим: держит в enabled только группу ближайшего прогона, пока '
  'football-digest не выкачена с поддержкой poll_group. Снятие расписано в '
  'шапке digest_poll_rotation.sql.';

revoke all on function public.rotate_digest_poll_group() from public, anon, authenticated;
grant execute on function public.rotate_digest_poll_group() to service_role;

-- ---------------------------------------------------------------------------
-- Расписание: за минуту до каждого прогона дайджеста.
-- ---------------------------------------------------------------------------
select cron.unschedule('rotate-digest-poll-group')
 where exists (select 1 from cron.job where jobname = 'rotate-digest-poll-group');

select cron.schedule(
  'rotate-digest-poll-group',
  '9-59/10 * * * *',
  $$select public.rotate_digest_poll_group()$$
);

-- Первый прогон сразу: иначе до ближайшей девятой минуты в enabled стоит
-- то, что осталось от ручной правки, а это ровно «клубы выключены».
select public.rotate_digest_poll_group();
