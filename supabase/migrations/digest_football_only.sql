-- ============================================================================
-- Дайджест — про футбол. Отсев чужих видов спорта.
--
-- ЧТО СЛУЧИЛОСЬ. `digest_topics()` выдавала десять горячих тем суток, и одной
-- из них был КРИКЕТ: «Super Giants claim Hundred title with thrilling
-- last-gasp win over Rockets». Тема набрала три издания и шесть заголовков,
-- то есть по всем признакам выглядела горячей — она и была горячей, просто не
-- про тот вид спорта.
--
-- ОТКУДА. Не все ленты футбольные, хотя список источников выглядит футбольным.
-- Замер по первому сегменту адреса за всё содержимое `news_items`:
--
--     football 789   futbol 452   futebol 60   soccer 15      <- футбол
--     martial 58     modalidades 38   tennis 27   hockey 23   <- нет
--     rhythmic-gymnastics 16   swimming 16   cricket 6   golf 5
--
-- Лента Sky Sports `rss/12040` оказалась ОБЩЕСПОРТИВНОЙ: 11 из 26 материалов
-- за двое суток — гольф, NFL, скачки, F1, крикет. У Sky есть футбольная лента
-- `rss/11095` (19 из 20 материалов в `/football/`), и переключение на неё —
-- `UPDATE` в `digest_source`, без деплоя. Это делается в `digest_sources.sql`
-- рядом и снимает бо́льшую часть проблемы В ИСТОЧНИКЕ, что всегда лучше
-- фильтра после.
--
-- Остаются Спорт-Экспресс и Record: у первого футбольной ленты нет вовсе
-- (`/services/materials/news/football/` отвечает 404, `/football/news/` — 403),
-- у второго лента общая и раздел «modalidades» — это буквально «другие виды
-- спорта».
--
-- ПОЧЕМУ ЧЁРНЫЙ СПИСОК, А НЕ БЕЛЫЙ. Белый («пускать только football/futbol/
-- futebol/soccer») отрезал бы Foot Mercato целиком: у него в адресе раздела
-- НЕТ, первый сегмент — слаг статьи
-- («a2043712114050897705-barca-rodri-attendu-a-barcelone-ce-lundi»). Двести с
-- лишним заметок исчезли бы молча.
--
-- И это осознанно противоположный выбор тому, что сделан в сопоставлении имён
-- ESPN, где предпочтён пропуск, а не ошибка. Здесь цена перевёрнута:
-- просочившийся крикет читатель видит и морщится, а потерянный футбол не
-- видит никто. Фильтр обязан ошибаться в сторону «пропустить лишнее».
--
-- ПОЧЕМУ ПРИ ЧТЕНИИ, А НЕ ПРИ ЗАПИСИ. Отсев в Edge Function требовал бы
-- деплоя — а перенос исходника агентом однажды уже вписал в прод `ᑑ` вместо
-- `ё` (см. §9 карты). И, главное, отсев при записи не чинит уже записанное:
-- крикет, лежащий в таблице сейчас, продолжал бы всплывать темой ещё сутки.
--
-- ⚠️ ЗАВИСИМОСТЬ. Этот файл применяется ПЕРВЫМ: `digest_news` в
-- `football_digest.sql` и `digest_topics` в `digest_topics.sql` зовут
-- `non_football_url()` и без неё не создадутся.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Раздел сайта — это ПЕРВЫЙ сегмент пути, и брать надо именно его.
--
-- Поиск подстроки по всему адресу дал бы ложные срабатывания на живом футболе:
-- «racing» есть в Racing Club, Racing Santander и RC Lens, а «other» — внутри
-- десятка слагов. Первый сегмент — это раздел издания, и в нём случайных слов
-- не бывает.
--
-- Список ведётся ПО ЗАМЕРУ: сюда попадает то, что реально приезжало в
-- `news_items`, плюс очевидные соседи тех же изданий. Новый вид спорта
-- просочится один раз и будет виден на экране — это дешевле, чем белый список,
-- который теряет молча.
-- ---------------------------------------------------------------------------
create or replace function public.non_football_url(p_url text)
returns boolean
language sql
immutable
as $$
  select split_part(
           regexp_replace(coalesce(p_url, ''), '^https?://[^/]+', ''), '/', 2
         ) in (
    -- Замерено в news_items
    'cricket', 'golf', 'nfl', 'racing', 'f1', 'tennis', 'hockey', 'boxing',
    'basketball', 'swimming', 'synchronized-swimming', 'rhythmic-gymnastics',
    'artistic-gymnastics', 'figure-skating', 'figureskating', 'olympics',
    'cybersport', 'martial', 'modalidades', 'record-gaming', 'other',
    -- Соседние разделы тех же изданий: ни одно футбольное издание не кладёт
    -- футбол в раздел с таким именем, поэтому пустить их вперёд безопасно.
    'nba', 'nhl', 'mlb', 'rugby-union', 'rugby-league', 'rugby', 'mma', 'ufc',
    'darts', 'snooker', 'cycling', 'athletics', 'volleyball', 'handball',
    'chess', 'biathlon', 'skiing', 'gymnastics', 'motorsport', 'esports',
    'martial-arts', 'wrestling', 'baseball'
  );
$$;

comment on function public.non_football_url(text) is
  'Адрес заметки указывает на чужой вид спорта. Проверяется ПЕРВЫЙ сегмент '
  'пути — раздел издания; поиск подстроки ловил бы Racing Club и RC Lens.';

grant execute on function public.non_football_url(text)
  to anon, authenticated, service_role;
