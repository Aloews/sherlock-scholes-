-- Ролики с YouTube — каждые 10 минут вместо раза в час.
--
-- Владелец: «Обновление видео с ютуб сделай чаще».
--
-- ⚠️ РОТАЦИЯ ПО `poll_group` БЫЛА РАССЧИТАНА НА 47 КЛУБНЫХ КАНАЛОВ, А ИХ
-- ВОСЕМЬ. Расчёт в шапке `digest_club_channels.sql` считал 47 клубов и 9 лиг и
-- поэтому раскладывал клубы по шести группам — по одной за прогон. Замер
-- 07.09.2026 по самой таблице: включённых каналов 17, из них 9 в группе 0
-- (каждый прогон) и 8 в группе 2 (раз в час). То есть шестью группами делится
-- ровно одна восьмёрка, и семь прогонов из восьми она просто молчит.
--
-- РАСХОД, ПОСЧИТАННЫЙ ПО ФАКТУ, А НЕ ПО ПЛАНУ. Канал стоит ДВЕ единицы
-- (playlistItems + videos.list), прогон идёт 144 раза в сутки:
--     было: 9×2×144 + 8×2×24  = 2976 единиц (30% суточной квоты 10 000)
--     стало: 17×2×144         = 4896 единиц (49%)
-- Половина квоты остаётся свободной — ровно тот запас, который и заложен в
-- шапке функции.
--
-- ⚠️ ЭТО ОДИН UPDATE, А НЕ ПРАВКА ФУНКЦИИ, И ЭТО НАМЕРЕННО. Список источников
-- живёт в таблице ровно затем, чтобы такие вещи не стоили деплоя: `poll_group
-- = 0` уже значит «каждый прогон», и функция это умеет с самого начала.
update public.digest_source
   set poll_group = 0
 where enabled and kind = 'channel' and poll_group <> 0;

comment on column public.digest_source.poll_group is
  '0 — опрашивать каждый прогон (каждые 10 минут), 1..6 — раз в час. Держит '
  'квоту YouTube: канал стоит 2 единицы, прогонов 144 в сутки, квота 10 000. '
  'С 07.09.2026 все 17 каналов в группе 0 — 4896 единиц, 49% квоты.';
