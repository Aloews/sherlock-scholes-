-- ============================================================================
-- Докуда вообще расписано.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, ЕСЛИ ЕСТЬ САМА ТАБЛИЦА. Затем же, зачем заведена
-- `player_stats_freshness()`: без неё пустота отвечает на два разных вопроса
-- одинаково.
--
-- Провайдер публикует расписание примерно на три недели вперёд. Значит
-- месячная сетка на следующий месяц у него почти пуста — и нарисованная без
-- этой функции, она читается как «в сентябре футбола нет». Это неправда, и
-- неправда дорогая: игрок делает из неё вывод и не возвращается.
--
-- Горизонт — это ровно то, что превращает пустую клетку из утверждения
-- «матчей не будет» в честное «пока не знаем».
--
-- ⚠️ ГОРИЗОНТ — ЭТО НЕ `max(commence_at)`, И ЭТО НЕ ПРИДИРКА. В таблице сейчас
-- сплошное покрытие с 10 по 30 августа и ОДИН матч 24 сентября — какой-то
-- турнир объявил дату заранее. По максимуму горизонт равнялся бы 24 сентября,
-- и двадцать пять пустых дней между ними стали бы «известными и пустыми», то
-- есть утверждением «матчей не будет» — ровно тем враньём, ради отказа от
-- которого эта функция и написана. Один далёкий матч не делает известным
-- месяц вокруг себя.
--
-- Поэтому `published_until` — последний день ПЕРЕД первым разрывом длиннее
-- недели. Неделя выбрана не на глаз: все эти турниры играют минимум раз в
-- неделю, поэтому дыра длиннее семи дней означает «не опубликовано», а не
-- «футбола нет». Пауза на сборные горизонт не срежет, потому что в таблице
-- два десятка турниров и МЛС с Лигой MX играют, когда Европа отдыхает; но
-- если однажды останутся только европейские лиги, это место придётся
-- пересмотреть — оно перечислено в §9 карты.
--
-- ⚠️ КОЭФФИЦИЕНТОВ ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ. Функция смотрит только в
-- `fixtures`; `fixture_odds` не читается ни здесь, ни где-либо ещё на пути к
-- экрану — у неё нет ни гранта, ни политики (§4 LIVE_FOOTBALL_HANDOFF.md).
-- ============================================================================

create or replace function public.fixtures_horizon()
returns table (
  first_match     timestamptz,
  -- Самый далёкий матч, о котором вообще известно. Не горизонт: см. выше.
  last_match      timestamptz,
  -- Докуда расписание СПЛОШНОЕ. Именно это красит клетки календаря.
  published_until timestamptz,
  matches         integer,
  -- Когда счета обновлялись в последний раз. Экран обязан показывать возраст,
  -- а не счёт как таковой: счёт пятнадцатиминутной давности, поданный как
  -- текущий, — это то самое враньё, ради отказа от которого выбрасывали
  -- википедию как источник счетов.
  scores_at       timestamptz
)
language sql
stable
set search_path = public
as $$
  with days as (
    select distinct date_trunc('day', commence_at) as d from public.fixtures
  ),
  runs as (
    select d, lead(d) over (order by d) as next_d from days
  )
  select
    (select min(commence_at) from public.fixtures),
    (select max(commence_at) from public.fixtures),
    -- Первый день, после которого расписание обрывается: либо дальше ничего
    -- нет вовсе, либо до следующего матча больше недели.
    (select min(d) from runs where next_d is null or next_d - d > interval '7 days'),
    (select count(*)::integer from public.fixtures),
    (select max(scores_at) from public.fixtures);
$$;

-- Читать может кто угодно: здесь три даты и число, ничего личного.
-- ⚠️ Грант и политика — разные ворота, и Postgres проверяет грант ПЕРВЫМ. У
-- функции политик не бывает, но грант нужен обязательно.
revoke all on function public.fixtures_horizon() from public;
grant execute on function public.fixtures_horizon() to anon, authenticated, service_role;

