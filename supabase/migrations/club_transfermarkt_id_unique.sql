-- Идентификатор клуба на Transfermarkt принадлежит РОВНО ОДНОМУ клубу.
--
-- ЧТО СЛУЧИЛОСЬ. Мост «клуб → verein» строится голосованием игроков состава,
-- и голосование задумывалось как защита от одного устаревшего игрока (у
-- «Байерна» такой привёл мост в «Аугсбург»). Оно не спасло: у «Страсбура» и
-- «Челси» общий владелец и игроки ходят между клубами, поэтому ДВОЕ из пяти
-- голосовавших за «Страсбур» уже числились в «Челси». Двух голосов хватило,
-- и `strasbourg alsace` получил verein/631 — «Челси».
--
-- Снаружи это выглядело безупречно: 28 игроков, у всех цена, состав
-- правдоподобный. Поймалось не глазами, а тем, что Коул Палмер, Эстевао,
-- Гиттенс и Хато оказались в ДВУХ заявках сразу — а так не бывает.
--
-- ⚠️ ВТОРАЯ УЛИКА (`roster_confirms`) ЗДЕСЬ БЕСПОЛЕЗНА ПО ПОСТРОЕНИЮ: она
-- требует, чтобы голосовавшие нашлись в выкачанном ростере, — а они там и
-- есть, они же за него и голосовали. Проверка, подтверждающая сама себя.
--
-- ПОЧЕМУ ИНДЕКС, А НЕ ЕЩЁ ОДНА ПРОВЕРКА В ПИТОНЕ. Сравнивать имя клуба на
-- странице с нашим — значит завести вторую копию правила сопоставления вне
-- SQL. А ограничение выражается без единого имени: два клуба не могут иметь
-- один verein. Такой же индекс на `cards.wikidata_qid` уже поймал 19 дублей
-- колоды, которых сравнение имён не видело.

-- 1. Починка. «Челси» = verein/631 верно, значит неверен «Страсбур».
--    Его ростер — это выкачанная заявка «Челси», и он удаляется целиком:
--    оставить его значит показывать игроков «Челси» на экране «Страсбура».
delete from club_roster
 where club_key = 'strasbourg alsace'
   and tm_player_id in (select tm_player_id from club_roster where club_key = 'chelsea');

update football_club set transfermarkt_id = null
 where club_key = 'strasbourg alsace' and transfermarkt_id = '631';

-- 2. Впредь — невозможно. Частичный: клубов без моста большинство.
create unique index if not exists football_club_transfermarkt_id_uniq
    on football_club (transfermarkt_id)
 where transfermarkt_id is not null;

comment on index football_club_transfermarkt_id_uniq is
  'Один verein — один клуб. Ловит мост, уехавший на чужой клуб: у «Страсбура» '
  'вышло verein/631 («Челси»), потому что игроки ходят между клубами одного '
  'владельца и двух голосов хватило.';
