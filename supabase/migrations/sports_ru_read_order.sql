-- Очередь чтения sports.ru: сперва важное, но без голодания
-- ==========================================================
--
-- ⚠️ БЮДЖЕТ ВЫБИРАЕТСЯ ДО КОНЦА КАЖДУЮ НОЧЬ, И РЕШАЛО, КОГО ПРОЧТУТ, НЕ ТО.
-- Замер по прогону 20.09.2026:
--
--     pages fetched: 3500              бюджет исчерпан полностью
--     players to read: 5755
--     budget spent after 1154 players  прочитано 20 %
--
-- Порядок был `checked_at.asc.nullsfirst, card_id.asc`. Первый ключ честный:
-- он держит ротацию, чтобы не перечитывать одну и ту же голову каждую ночь.
-- А всё остальное решал второй — номер карточки, то есть случайный UUID.
--
-- Это ровно та ошибка, которую уже чинили в проходе догадки (шапка
-- `_order_for_guess` в football_scraper/sports_ru_stats.py): там по `id` в
-- бюджет не попадали Анри, Агуэро, Родриго и Карвахаль, пока перебирались
-- тысячи карточек без единого просмотра в википедии. Проход ЧТЕНИЯ того же
-- лечения не получил, и заметил это владелец, а не проверка.
--
-- ⚠️ РОТАЦИЯ СОХРАНЕНА, И ЭТО ГЛАВНОЕ ОГРАНИЧЕНИЕ. Отсортировать просто по
-- стоимости значило бы читать одних и тех же дорогих каждую ночь, а дешёвых
-- никогда. Поэтому сперва СУТКИ последней проверки (ни разу не читанные
-- впереди), и только ВНУТРИ суток — стоимость клуба и известность.
-- Прочитанная карточка уходит в завтрашнее ведро сама.
--
-- Сутки, а не точное время: ночной прогон штампует `checked_at` в пределах
-- одного часа, и по точному времени каждый оказался бы в своём ведре по
-- одному — сортировка по важности не сработала бы ни разу.
--
-- Замер выигрыша на боевой очереди 20.09.2026, первые 1154 строки (столько
-- успевает прогон):
--
--                                     старый порядок   новый
--     карточек с известностью 90+            11          28
--     стоимость клубов, млрд евро         108.4       147.6
--
-- ⚠️ ПРЕДСТАВЛЕНИЕ, А НЕ ФУНКЦИЯ, И ЭТО НЕ ВКУСОВЩИНА. Ответ RPC через
-- PostgREST режется по `db-max-rows` до тысячи строк — молча, с кодом 200
-- (разбор в шапке класса `Db`). Очередь длиннее пяти тысяч, и функция
-- урезала бы её впятеро, ничего об этом не сказав. У представления ключи
-- сортировки лежат КОЛОНКАМИ, поэтому обход идёт тем же постраничным
-- `select()`, что и везде, со всеми его проверками.
--
-- Цена смещения замерена, потому что здесь уже был 504 на шестой странице
-- `cards`: по тысяче строк на страницу — 996, 994, 1070 и 905 мс на
-- смещениях 0, 1000, 3000 и 5000. Роста нет: цена представления в CTE, а не
-- в смещении.
create or replace view public.sports_ru_read_order as
  with club_worth as (
    select r.club_key, sum(r.market_value_eur) as value_eur
      from club_roster r
     where r.market_value_eur is not null
     group by r.club_key
  )
  select p.card_id,
         p.slug,
         p.name_ru,
         p.checked_at,
         -- Ведро ротации. NULL — ни разу не читали, идёт первым.
         date_trunc('day', p.checked_at) as checked_day,
         coalesce(w.value_eur, 0)::bigint as club_value_eur,
         coalesce(c.fame, 0)::numeric      as fame
    from sports_ru_player p
    left join cards c on c.id = p.card_id
    left join card_current_club cc on cc.card_id = p.card_id
    left join club_worth w on w.club_key = cc.club_key;

-- Очередь сбора: её читает только ночной обход под сервисным ключом.
revoke all on public.sports_ru_read_order from public, anon, authenticated;
grant select on public.sports_ru_read_order to service_role;
