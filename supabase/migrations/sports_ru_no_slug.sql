-- ============================================================================
-- Память о том, у кого страницы на sports.ru НЕТ.
--
-- ⚠️ ЗАЧЕМ ХРАНИТЬ ОТКАЗ. Шаг догадки в `football_scraper/sports_ru_stats.py`
-- предлагает слаг из латинского имени карточки и проверяет его страницей.
-- Успех попадал в `sports_ru_player`, а отказ — НИКУДА. Кандидаты при этом
-- перебирались в порядке `id`, и бюджет прогона кончался на первых сотнях:
--
--   замер по прогону 11.09.2026 — угаданы ранги с 5-го по 368-й из 24 093
--
-- То есть каждую ночь пробовались ОДНИ И ТЕ ЖЕ карточки, а остальные двадцать
-- тысяч не пробовались ни разу. Владелец просил статистику ВСЕХ игроков; при
-- таком порядке это недостижимо в принципе, а не медленно.
--
-- Отметка отказа — это МЕСТО В ОЧЕРЕДИ, А НЕ ПРИГОВОР. Очередь строится по
-- (сколько раз пробовали, когда пробовали в последний раз), и «ни разу» идёт
-- первым. Насовсем не выбрасывается никто: страница у игрока может появиться
-- завтра, и тогда до него дойдёт очередь снова. Успешная догадка строку
-- удаляет — иначе однажды не найденный игрок навсегда остался бы в хвосте.
--
-- ⚠️ ЭТО НЕ КЭШ ОТРИЦАТЕЛЬНОГО ОТВЕТА, и разница существенна. Кэш отвечал бы
-- «страницы нет» вместо запроса; здесь запрос по-прежнему делается, просто
-- позже тех, кого не спрашивали вовсе.
--
-- Читает и пишет только сборщик (service_role). Экранам эта таблица не нужна:
-- она про устройство обхода, а не про игрока.
-- ============================================================================
create table if not exists public.sports_ru_no_slug (
  card_id  uuid primary key references public.cards(id) on delete cascade,
  tried_at timestamptz not null default now(),
  -- Сколько раз уже пробовали. Растёт — значит кандидат уходит дальше в
  -- хвост, но не исчезает.
  tries    integer not null default 1
);

comment on table public.sports_ru_no_slug is
  'Карточки, которым шаг догадки НЕ нашёл страницы на sports.ru. Память об '
  'отказе: без неё каждую ночь перебирались одни и те же первые сотни, а '
  'остальные двадцать тысяч не пробовались ни разу.';

alter table public.sports_ru_no_slug enable row level security;
-- Политики нет намеренно: с включённым RLS и без политики таблица закрыта
-- для anon и authenticated, а service_role её обходит.
grant select, insert, update, delete on public.sports_ru_no_slug to service_role;
