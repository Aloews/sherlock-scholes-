-- ОЧЕРЕДЬ ТАЛАНТОВ: кого заводить в колоду следующим — и чего делать нельзя.
--
-- Владелец: «в некоторых клубах есть игроки по версии Soccer Wiki, а во
-- внутренней базе этого игрока нет. Настрой парсеры корректно, чтобы выявлять
-- самых молодых и талантливых игроков, а не только „игроков-проектов“».
--
-- ЗАМЕР, С КОТОРОГО ВСЁ НАЧАЛОСЬ. В `soccerwiki_player` 57 650 строк, и 42 840
-- из них БЕЗ КАРТОЧКИ. Со стороны Transfermarkt дыры нет вовсе (`club_roster`:
-- 24 492 строки, ни одной без карточки) — весь пробел здесь.
--
-- ⚠️ ПРЕЖНИЙ ОТБОР БЫЛ НЕ ОТБОРОМ, А ПОРЯДКОМ В ТАБЛИЦЕ.
-- `cards_from_roster.py` берёт первые N строк `order=tm_player_id`: колода
-- наполняется теми, у кого меньше идентификатор, а не теми, кто важен. Молодой
-- талант мог не попасть в неё никогда — и это ровно то, на что жалуется
-- владелец.
--
-- ⚠️ И ПРОСТОЙ ПОРОГ ПО РЕЙТИНГУ НЕ ГОДИТСЯ — ЭТО ЗАМЕРЕНО. Рейтинг растёт с
-- возрастом, поэтому общий порог отбирает ветеранов и пропускает ровно тех,
-- кого просили найти:
--
--     возраст   всего   без карточки   средний рейтинг
--     ≤19       5 780   4 533          66.2
--     20–21     8 096   5 997          69.0
--     22–23     8 253   5 917          71.8
--     24–28    18 087  12 906          75.0
--     29+      17 434  13 487          76.5
--
-- ЧТО СЧИТАЕТСЯ ТАЛАНТОМ: рейтинг ОТНОСИТЕЛЬНО СВОИХ РОВЕСНИКОВ. У
-- восемнадцатилетнего 86 — исключение, у тридцатилетнего — обычное дело.
-- Первые места очереди: Эстевао (19, «Челси»), Кенан Йылдыз (21, «Ювентус»),
-- Мбайе (18, «Астон Вилла»), Ахонор (18, «Кристал Пэлас»), Крупи (20,
-- «Борнмут») — то есть именно молодые и именно заметные.
--
-- ⚠️ РОВЕСНИКИ БЕРУТСЯ ПОЛОСОЙ, А НЕ ТОЧНЫМ ВОЗРАСТОМ, И ЭТО ПОЧИНКА УЖЕ
-- ПОЙМАННОЙ ОШИБКИ. По точному возрасту пятнадцатилетний с рейтингом 70
-- получал перцентиль 1.000 — просто потому, что пятнадцатилетний в выборке
-- один. Этот проект уже спотыкался о крошечные группы ровесников на экране
-- «громкость против игры». Отсюда `band_n >= 200`.
--
-- ⚠️ И АБСОЛЮТНЫЙ ПОЛ ТОЖЕ ЕСТЬ. Один перцентиль вывел бы наверх лучшего среди
-- слабых; порог 75 отсекает это, оставаясь ниже среднего у взрослых.
--
-- ⚠️⚠️ ОЧЕРЕДЬ — НЕ КОМАНДА «ЗАВЕСТИ КАРТОЧКУ», И ЭТО ГЛАВНОЕ ОГРАНИЧЕНИЕ.
-- Замер по первым тремстам: 54 из них В КОЛОДЕ УЖЕ ЕСТЬ — просто строка
-- Soccer Wiki к карточке не привязана, — и 246 действительно новые. Заводить,
-- не посмотрев на `in_deck`, значит плодить двойников; двойник в колоде хуже
-- дыры, потому что дыру видно, а его нет.
--
-- ⚠️ ПОЧЕМУ ПРИВЯЗКА НЕ СРАБАТЫВАЕТ. `link_soccerwiki_by_name` сверяет
-- `lower(btrim(name))` с `cards.name_en` ТОЧНО. Soccer Wiki пишет фамилию
-- первой и склеивает: «Gonzalez Pedri», «Hernández Rodri», «Willian Estêvão» —
-- а в колоде лежат «Pedri», «Rodri», «Estêvão».
--
-- ⚠️ И ПОЧИНИТЬ ЭТО «ПО ПОСЛЕДНЕМУ СЛОВУ» НЕЛЬЗЯ, ЭТО ПРОВЕРЕНО. Совпадений по
-- последнему слову 1952, но подтверждённых КЛУБОМ из них только 231 —
-- остальное однофамильцы. Связать их значило бы приписать игроку чужую
-- статистику; в этом проекте такое уже было («Крузейро» ↔ `cruz azul`).
--
-- ⚠️ МАССОВОЕ ЗАВЕДЕНИЕ КАРТОЧЕК ОТСЮДА ТРЕБУЕТ МОСТА, КОТОРОГО ПОКА НЕТ.
-- `cards_from_roster.py` заводит карточку по цепочке tm_player_id → P2446 →
-- QID; у игрока Soccer Wiki идентификатора Transfermarkt нет. Поиск по имени в
-- Викиданных — тот самый путь, от которого проект отказался сознательно
-- (комментарий в `cards_from_roster.py`: «Поиска по имени здесь нет вовсе»).
-- Пока моста нет, очередь — это список для глаз, а не вход конвейера.
-- ============================================================================

drop view if exists player_talent_queue;

create view player_talent_queue as
  with base as (
    select p.pid, p.name, p.full_name, p.age, p.rating, p.position,
           p.nation, p.nation_code, p.born_on, p.photo_url,
           c.club_key, f.name as club_name, f.league, f.country
      from soccerwiki_player p
      join soccerwiki_club c on c.club_id = p.club_id
      join football_club f on f.club_key = c.club_key
     where p.card_id is null
       and p.rating is not null and p.age is not null
       -- Клуб обязан играть в известной нам лиге: иначе «талант» нечем
       -- подтвердить — ни матчей, ни турнира у нас нет.
       and f.league is not null and f.kind = 'club'
  ), banded as (
    select *,
           case when age <= 17 then '≤17' when age <= 19 then '18-19'
                when age <= 21 then '20-21' when age <= 23 then '22-23'
                when age <= 28 then '24-28' else '29+' end as band
      from base
  ), ranked as (
    select *,
           count(*) over (partition by band) as band_n,
           percent_rank() over (partition by band order by rating) as among_peers
      from banded
  ), named as (
    select *,
           lower(btrim(name)) as k_name,
           lower(btrim(split_part(name, ' ',
                       array_length(string_to_array(name, ' '), 1)))) as k_last
      from ranked
     where band_n >= 200 and rating >= 75
  )
  select n.pid, n.name, n.full_name, n.age, n.band, n.rating, n.position,
         n.nation, n.nation_code, n.born_on, n.photo_url,
         n.club_key, n.club_name, n.league, n.country,
         round(n.among_peers::numeric, 4) as among_peers,
         n.band_n,
         -- «Похоже, карточка уже есть»: точное совпадение имени целиком ИЛИ
         -- последнего слова. Это НЕ доказательство — это повод посмотреть
         -- глазами прежде, чем заводить.
         exists (select 1 from cards c
                  where c.active and c.category = 'player' and c.name_en is not null
                    and lower(btrim(c.name_en)) in (n.k_name, n.k_last)) as in_deck,
         -- Порядок: сначала насколько выделяется среди ровесников, потом
         -- молодость. Молодость НЕ складывается с талантом в одно число —
         -- сумма непрозрачна, а два ключа сортировки видно глазами.
         row_number() over (order by round(n.among_peers::numeric, 3) desc,
                                     n.age asc, n.rating desc, n.pid asc) as place
    from named n;

grant select on player_talent_queue to service_role;
