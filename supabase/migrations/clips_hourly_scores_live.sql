-- Ролики — раз в час, счёт идущего матча — каждые пять минут.
--
-- Владелец: «роллики можно раз в час, а вот счет идущих матчей, стоит
-- обновлять, чтобы можно было отследить ход матча и присоединиться к
-- просмотру».
--
-- Это ровно обратный размен тому, что делал `digest_clips_faster.sql`, и он
-- обоснован: ролик, вышедший на десять минут позже, читателю не виден вовсе, а
-- счёт, отставший на два часа, — это уже не «ход матча», а итог.
--
-- ⚠️ РАСЧЁТ КВОТЫ ПО ФАКТУ ТАБЛИЦЫ, А НЕ ПО ПАМЯТИ. Замер 09.09.2026:
-- нужных каналов 56 (не 17, как считала шапка digest_clips_faster.sql —
-- каналов с тех пор прибавилось). Канал стоит ДВЕ единицы
-- (playlistItems + videos.list).
--
--     было:  17 в группе 0 × 2 × 144  = 4896
--          + 39 по группам 1..6 × 2 × 24 = 1872
--          ─────────────────────────────────────
--            6768 единиц в сутки — 68% квоты 10 000
--
--     стало: 56 по группам 1..6 × 2 × 24 = 2688 — 27% квоты
--
-- Освобождается 4080 единиц в сутки. При почасовом опросе канал стоит 48
-- единиц, то есть запаса хватает ещё на восемь десятков каналов — это и есть
-- бюджет под «добавь другие официальные каналы команд».
--
-- ⚠️ ГРУППА 2 БЫЛА ПУСТА. Ротация раскладывает каналы по шести группам и
-- зовёт по одной за прогон; пустая группа значит, что один прогон из шести
-- уходит впустую, а остальные пять несут нагрузку за него. Раскладка ниже
-- ровная — по `row_number`, а не по тому, кого когда добавили.
update public.digest_source d
   set poll_group = g.grp
  from (
    select id, (row_number() over (order by id) % 6)::int + 1 as grp
      from public.digest_source
     where kind = 'channel' and wanted
  ) g
 where d.id = g.id;

comment on column public.digest_source.poll_group is
  '0 — опрашивать каждый прогон (каждые 10 минут), 1..6 — раз в час. Держит '
  'квоту YouTube: канал стоит 2 единицы, прогонов 144 в сутки, квота 10 000. '
  'С 09.09.2026 все каналы в группах 1..6 — 2688 единиц, 27% квоты; освободили '
  'место под новые каналы и под частый счёт.';

-- ─── Счёт идущих матчей ─────────────────────────────────────────────────────
--
-- ⚠️ ПЯТЬ МИНУТ ЗДЕСЬ БЕСПЛАТНЫ РОВНО ПО ТОЙ ЖЕ ПРИЧИНЕ, ПО КОТОРОЙ БЫЛИ
-- БЕСПЛАТНЫ ДВА ЧАСА. `fetch_espn_scores` сперва спрашивает
-- `espn_leagues_in_play()`, и тот отвечает пустотой, когда в окне
-- [now − 4 часа, now + 15 минут] нет ни одного несыгранного матча. Ночью
-- задание просыпается, видит ноль лиг и НЕ ДЕЛАЕТ НИ ОДНОГО запроса наружу —
-- ни платного, ни бесплатного. Растёт не расход, а частота ТАМ, ГДЕ ИДЁТ ИГРА.
--
-- Почему именно пять: гол — событие, которое читатель хочет увидеть, пока оно
-- ещё новость. При двух часах он узнаёт счёт, когда матч кончился, и
-- «присоединиться к просмотру» уже не к чему. Меньше пяти смысла нет: ESPN
-- сам обновляет свой счёт не чаще.
--
-- Минута :3 намеренно не круглая — в этом инстансе pg_cron уже толпятся
-- задания на :00, :05, :10, :20, :35, :50, и лишнее совпадение по минуте
-- означало бы, что они делят один пул соединений pg_net.
select cron.alter_job(
  (select jobid from cron.job where jobname = 'fetch-espn-scores'),
  schedule => '3-58/5 * * * *'
);
