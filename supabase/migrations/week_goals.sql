-- Дыра между двумя окнами, в которую провалился Суперкубок Европы.
--
-- ЖАЛОБА БЫЛА «НАДО ЧАЩЕ ОБНОВЛЯТЬ», А ЧАСТОТА НИ ПРИ ЧЁМ. Ролик был скачан
-- вовремя и лежал в базе всё это время:
--
--   2026-08-14 Пт 13:00  UEFA  «Winning the Super Cup for his team!»  127 959
--
-- Показать его было негде. На экране два раздела, и оба его не берут:
--
--   digest_weekend_goals — последние ЗАВЕРШИВШИЕСЯ выходные, 8–10 августа.
--                          14 августа туда не попадает и не попадёт никогда.
--   digest_goals         — последние сутки. В субботу вечером ролику пятницы
--                          уже 30 часов, и он выпал.
--
-- То есть ВСЁ, ЧТО ИГРАЕТСЯ С ПОНЕДЕЛЬНИКА ПО ПЯТНИЦУ, живёт на экране ровно
-- сутки и исчезает: Суперкубок, Лига чемпионов, Кубок Италии, отборочные. Для
-- приложения про футбол это не мелочь — это половина футбола.
--
-- Чинится третьим окном, а не расширением существующих. Разделы отвечают на
-- разные вопросы, и смешать их значило бы потерять оба ответа: «что было в
-- выходных» — это итог тура, «что нового сегодня» — это лента.

/**
 * Лучшее за неделю МИМО ВЫХОДНЫХ.
 *
 * Окно — семь суток назад, МИНУС то, что уже показано в блоке выходных: иначе
 * один и тот же гол стоял бы на экране дважды, и второй раз выглядел бы как
 * ошибка. Вычитание идёт по тем же границам weekend_bounds, а не по «примерно
 * субботе», чтобы два раздела не разошлись при смене правила.
 *
 * Порядок тот же, что у выходных: сначала голы, внутри — по просмотрам.
 * Одинаковый порядок в двух разделах — это обещание, что «лучшее» на экране
 * значит одно и то же в обоих местах.
 */
create or replace function digest_week_goals(p_limit int default 12)
returns table (
  video_id text, title text, channel text, published_at timestamptz,
  thumb_url text, views bigint, likes integer, is_goal boolean
)
language sql stable security definer set search_path = public as $$
  with b as (select starts_at, ends_at from weekend_bounds() limit 1)
  select g.video_id, g.title, g.channel, g.published_at, g.thumb_url,
         g.views, g.likes, looks_like_goal(g.title)
  from goal_clips g, b
  where g.published_at >= now() - interval '7 days'
    -- Не то, что уже стоит в блоке выходных.
    and not (g.published_at >= b.starts_at and g.published_at < b.ends_at)
  order by looks_like_goal(g.title) desc, g.views desc
  limit greatest(1, least(p_limit, 40))
$$;

-- Политика без гранта — это таблица, которую никто не может прочитать.
-- Грант стоит рядом с функцией по той же причине.
revoke all on function digest_week_goals(int) from public;
grant execute on function digest_week_goals(int) to anon, authenticated, service_role;

-- ─────────────────────────────────────────────────────────────────────────
-- Ролики живут дольше, чем окно, которое их показывает.
--
-- prune_digest резал goal_clips по 10 суткам, а недельное окно смотрит на 7 —
-- запас в трое суток. Но просмотры обновляются только у тех строк, что ещё
-- приходят в ленте канала, поэтому запас нужен именно такой: не меньше окна и
-- не настолько больше, чтобы копить мёртвое.
-- ─────────────────────────────────────────────────────────────────────────

-- ─────────────────────────────────────────────────────────────────────────
-- Чаще опрашивать источники — как и просили. Раз в 15 минут вместо раза в час.
--
-- Суперкубок это НЕ ЧИНИТ (ролик и так пришёл вовремя), но у частоты есть своя
-- причина: лента канала отдаёт около 15 последних записей, и в насыщенный
-- вечер — Кубок Италии выложил шесть роликов за три часа — редкий опрос может
-- не успеть до вытеснения. Четыре прогона в час против одного дают запас там,
-- где он действительно нужен.
-- ─────────────────────────────────────────────────────────────────────────
select cron.unschedule('fetch-football-digest');

select cron.schedule(
  'fetch-football-digest',
  '2,17,32,47 * * * *',
  $$select public.fetch_football_digest()$$
);
