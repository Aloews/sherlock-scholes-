-- ============================================================================
-- Голы собирались ШЕСТЬ ЧАСОВ В СУТКИ, и виноват был потолок модели.
--
-- Владелец: «чаще ищи свежие голы из лучших лиг».
--
-- ⚠️ ЗАМЕР, С КОТОРОГО ВСЁ НАЧАЛОСЬ. Ролики по часам поступления, двое суток:
--
--   12.09  00:00 — 270    13.09  00:00 — 258
--          01:00 —   3           01:00 —  16
--          …                     …
--          06:00 —   2           06:00 —   2
--          07:00 — НИЧЕГО        07:00 — НИЧЕГО
--          …до полуночи          …до полуночи
--
-- То есть конвейер работал с полуночи до половины седьмого UTC и был слеп
-- остальные семнадцать с половиной часов — РОВНО ВЕСЬ ЕВРОПЕЙСКИЙ ИГРОВОЙ
-- ДЕНЬ. Всплеск в полночь — это не «много матчей ночью», это накопленное за
-- сутки, которое влетает разом, когда счётчик обнуляется.
--
-- ⚠️ ПОЧЕМУ. `fetch_football_digest` резервировала 30 вызовов модели ПЕРЕД
-- КАЖДЫМ прогоном, безусловно и без возврата:
--
--   30 × 6 прогонов в час = 180 в час; потолок 1200 → исчерпан за 6 ч 40 мин
--
-- И `llm_budget` это подтверждает поимённо: 1200 из 1200, `updated_at` 06:30 —
-- и одиннадцатого, и двенадцатого, и тринадцатого.
--
-- ⚠️ А ВЫЗОВОВ НЕ БЫЛО НИ ОДНОГО. Замер тем же прогоном:
--
--   summaries_generated 0, titles_generated 0, llm_used false, clips_new 380
--
-- Выложенная функция читает флаг `llm` из тела и по умолчанию модель НЕ
-- ЗОВЁТ, а когда зовёт — резервирует по одному вызову перед каждым, сама
-- (`reserveLlmCall`). То есть внешний резерв на 30 не защищал ничего: он
-- сжигал суточный потолок на вызовы, которых не происходило, и останавливал
-- этим СБОР ГОЛОВ — единственное, ради чего прогон и нужен.
--
-- Резерв снят. Защита от траты осталась там, где она настоящая: флаг `llm`
-- (по умолчанию false) и поштучный резерв внутри функции. Выключатель
-- `llm_auto_switch` тоже на месте — он останавливает прогон целиком, и это
-- по-прежнему нужная кнопка.
--
-- ⚠️ ТЕЛО ТЕПЕРЬ ГОВОРИТ ПРЯМО `{"llm": false}`, а не пустое `{}`. Читается
-- одинаково, но пустое тело — это умолчание выложенной функции, а умолчание
-- может смениться. Намерение вызывающего должно быть написано.
-- ============================================================================
create or replace function public.fetch_football_digest()
returns bigint
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $function$
declare
  v_key text;
  v_id  bigint;
begin
  -- ⚠️ ВЫКЛЮЧАТЕЛЬ ОСТАЁТСЯ. Владелец однажды купил токены «на половину своих
  -- денег» и всё потратилось на пересказы; кнопка полной остановки нужна и
  -- после того, как трата перекрыта флагом.
  --
  --   update llm_auto_switch set enabled = false;   -- остановить всё
  --   update llm_auto_switch set enabled = true;    -- вернуть
  if not llm_auto_enabled() then
    raise warning 'fetch_football_digest: автомат выключен (llm_auto_switch), прогон пропущен';
    return null;
  end if;

  select decrypted_secret into v_key
    from vault.decrypted_secrets
   where name = 'fixtures_invoke_key';

  if v_key is null then
    raise warning 'fetch_football_digest: нет секрета fixtures_invoke_key — запуск пропущен';
    return null;
  end if;

  select net.http_post(
           url := 'https://konoavrduynecxblqfvq.supabase.co/functions/v1/football-digest',
           headers := jsonb_build_object(
             'Content-Type', 'application/json',
             'Authorization', 'Bearer ' || v_key),
           -- Модель не звать. Пересказы включаются вручную — телом
           -- {"llm": true}, и тогда их считает поштучный резерв внутри функции.
           body := '{"llm": false}'::jsonb,
           timeout_milliseconds := 120000
         ) into v_id;
  return v_id;
end;
$function$;

comment on function public.fetch_football_digest() is
  'Крон дайджеста. Модель НЕ зовёт (llm:false). Резерв потолка снят: он '
  'сжигал 1200 вызовов в сутки на несостоявшиеся пересказы и останавливал '
  'сбор голов в 06:30 UTC — разбор в digest_no_llm_reserve.sql.';

-- Счётчик за сегодня набран резервами под вызовы, которых не было
-- (summaries_generated 0 за весь день). Обнуляем, чтобы он снова описывал
-- РАСХОД, а не историю этой ошибки.
update public.llm_budget
   set calls = 0, updated_at = now()
 where day = (now() at time zone 'utc')::date;
