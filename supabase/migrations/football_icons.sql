-- ру-вики он «Паненка, Антонин». Список ключуется по ИМЕНИ КАРТОЧКИ, поэтому
-- здесь стоит имя как есть. Исправите имя карточки — поправьте и тут, иначе
-- тег молча перестанет ставиться.

create or replace function public.apply_football_icons()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  update cards c
     set tags = array_append(coalesce(c.tags, '{}'), 'icon')
    from football_icon i
   where c.name = i.card_name
     and c.active
     and not ('icon' = any(coalesce(c.tags, '{}')));
  get diagnostics v_count = row_count;

  -- Снять тег с выбывших: иначе список правится только в одну сторону, и
  -- убрать ошибку было бы нечем.
  update cards c
     set tags = array_remove(c.tags, 'icon')
   where 'icon' = any(coalesce(c.tags, '{}'))
     and not exists (select 1 from football_icon i where i.card_name = c.name);

  return v_count;
end;
$$;

comment on function public.apply_football_icons() is
  'Проставляет тег icon по таблице football_icon и снимает его с выбывших.';

alter table public.football_icon enable row level security;
drop policy if exists football_icon_read on public.football_icon;
create policy football_icon_read on public.football_icon
  for select to anon, authenticated using (true);
grant select on public.football_icon to anon, authenticated;
grant select, insert, update, delete on public.football_icon to service_role;
revoke all on function public.apply_football_icons() from public, anon, authenticated;
grant execute on function public.apply_football_icons() to service_role;

