-- ============================================================================
-- ИКОНЫ ФУТБОЛА — люди, изменившие игру.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ СУЩНОСТЬ. Владелец: «Паненка икона футбола, он повлиял на
-- историю футбола, добавь такие значимые фигуры». Он указывает на настоящую
-- дыру, и она измерима: у карточки «Антони Паненка» fame = 25 и тир common —
-- при том, что его именем называется способ бить пенальти.
--
-- Это не ошибка `fame`, а её граница. Она построена на просмотрах википедии и
-- отвечает на вопрос «кого читают СЕЙЧАС»; вклад в историю игры она не
-- измеряет и измерить не может. Из того, что у нас лежит, такую значимость не
-- вывести ничем — ни из голов (Паненка не бомбардир), ни из трофеев (их берут
-- целыми составами), ни из просмотров.
--
-- ⚠️ ЗНАЧИТ, ЭТО СПИСОК ЧЕЛОВЕКА, и признать это честнее, чем изобретать
-- формулу, которая выдаст правдоподобный порядок и будет неверной.
--
-- ⚠️ ТЕГ, А НЕ КАТЕГОРИЯ. Категория в этом проекте говорит, ЧТО на карточке
-- (игрок, клуб, стадион), и Паненка остаётся игроком. «Икона» — свойство
-- поверх, ровно как `legend` и `ballon_dor` рядом.
--
-- ⚠️ КЛЮЧ — ИМЯ, а не id. Список читается человеком и правится INSERT'ом без
-- деплоя, как `digest_source` и `club_alias_seed`.
-- ============================================================================

create table if not exists public.football_icon (
  card_name text primary key,
  note      text not null,
  added_at  timestamptz not null default now()
);

comment on table public.football_icon is
  'Люди, изменившие футбол. Список ЧЕЛОВЕКА: значимость такого рода не '
  'выводится ни из чего, что у нас лежит.';

comment on column public.football_icon.note is
  'ЧТО ИМЕННО он изменил. Обязательное поле, и это дисциплина, а не '
  'украшение: без него таблица за месяц превращается в список любимых '
  'игроков. Не можешь назвать вклад одной строкой — не икона.';

