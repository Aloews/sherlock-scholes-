-- ============================================================================
-- Краткая сводка по горячим темам — то, что собирает языковая модель.
--
-- ЧТО ЭТО. `digest_topics()` уже собирает тему как связную компоненту графа
-- заголовков, но НАЗЫВАЕТ её чужим заголовком — самым ранним в кластере. Для
-- «Sevilla-Rayo, 7 изданий, 160 заголовков» это выглядит как случайная фраза
-- из середины дня. Пересказа не было, и его нельзя получить из тех же
-- заголовков перестановкой: нужен текст, которого в лентах нет.
--
-- ⚠️ ПЛАТИМ ЗА НОВОСТЬ, А НЕ ЗА НАЖАТИЕ. Сводка делается ПО КНОПКЕ, то есть
-- сколько раз её нажмут — не наше решение. Поэтому ключ кэша — не время и не
-- игрок, а САМ НАБОР ТЕМ (`digest_topics_key`). Пока новости те же, все
-- нажатия всех игроков отвечают одной и той же записью и не стоят ничего;
-- новая генерация случается только тогда, когда сменились темы, а их меняет
-- конвейер раз в двадцать минут. Верхняя граница расхода задана НОВОСТЯМИ, и
-- игрок не может её сдвинуть, сколько бы ни жал.
--
-- Это и есть причина, по которой у таблицы нет ни колонки игрока, ни счётчика
-- обращений: ограничение стоит в ключе, а не в лимите, который надо помнить.
--
-- ЯЗЫК — ЧАСТЬ КЛЮЧА. Сводка пишется на языке читателя (девять локалей), и
-- сгенерированная для `ru` не годится для `es`. Генерируются только те языки,
-- которые кто-то открыл: девять сразу никто не оплачивает.
-- ============================================================================

create table if not exists public.digest_summary (
  -- Язык читателя, он же язык текста. Одна актуальная сводка на язык:
  -- история не нужна, устаревшая сводка бесполезна ровно в тот момент, когда
  -- сменились темы.
  lang         text primary key,

  -- Отпечаток набора тем, по которому сводка написана. Если текущий отпечаток
  -- совпадает — сводка актуальна, и генерировать нечего.
  topics_key   text not null,

  -- Пересказ и вывод одним текстом: делить их на колонки значит навязывать
  -- модели форму, а на девяти языках форма разная.
  summary      text not null,

  -- Какой моделью написано. Не для отчётности: смена модели меняет стиль, и
  -- без этой колонки «почему сводки вдруг стали другими» не ответить.
  --
  -- ⚠️ С 24.08.2026 здесь `провайдер/модель` — например `gateway/claude-opus-5`
  -- или `anthropic/claude-opus-4-8`. Провайдеров стало два (шлюз по base_url и
  -- прямой Anthropic, см. шапку functions/digest-summary/index.ts), и одного
  -- имени модели для ответа на тот же вопрос больше не хватает: сводка может
  -- смениться не потому, что сменилась модель, а потому, что отвечал другой
  -- провайдер. Старые строки без слэша — это прямой Anthropic до разделения.
  model        text not null,

  generated_at timestamptz not null default now()
);

comment on table public.digest_summary is
  'Сводка по горячим темам, по одной на язык. Ключ кэша — отпечаток набора тем, '
  'поэтому нажатия кнопки не умножают расход: платим за новость, а не за нажатие.';

-- ---------------------------------------------------------------------------
-- Отпечаток текущего набора тем.
--
-- Считается по АДРЕСАМ тем, а не по их заголовкам: заголовок кластера — это
-- самый ранний из вошедших, и он меняется, когда в кластер добавляется более
-- ранняя заметка, хотя сюжет тот же. Адрес привязан к конкретной заметке и
-- переживает это спокойнее.
--
-- Порядок фиксирован сортировкой: `digest_topics` возвращает темы по
-- убыванию числа изданий, и две темы с равным числом могут поменяться
-- местами между вызовами — без `order by` отпечаток бы «дрожал» и заставлял
-- генерировать заново на тех же новостях.
-- ---------------------------------------------------------------------------
create or replace function public.digest_topics_key(
  p_lang  text default 'ru',
  p_limit integer default 8,
  p_hours integer default 24
)
returns text
language sql
stable
as $$
  select coalesce(md5(string_agg(t.url, '|' order by t.url)), '')
  from public.digest_topics(p_lang, p_limit, p_hours) t;
$$;

-- ---------------------------------------------------------------------------
-- Права.
--
-- Пишет и читает только конвейер: клиент ходит в Edge Function, а не в
-- таблицу. Это не перестраховка — так решение «генерировать или отдать
-- готовое» остаётся на сервере, где известен и ключ модели, и отпечаток тем.
-- Дай клиенту читать таблицу напрямую, и он сможет показать вчерашнюю сводку
-- под сегодняшними темами.
--
-- ⚠️ Политика без гранта не работает, и грант без политики тоже: у таблицы
-- включён RLS, политик нет, и грант выдан ровно одной роли.
-- ---------------------------------------------------------------------------
alter table public.digest_summary enable row level security;
revoke all on public.digest_summary from anon, authenticated;
grant select, insert, update, delete on public.digest_summary to service_role;

grant execute on function public.digest_topics_key(text, integer, integer)
  to service_role;
