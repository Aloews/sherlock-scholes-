import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/**
 * МАРКИРОВКА ОБЯЗАНА СТОЯТЬ У ВСЕГО СОБРАННОГО, А НЕ У ТОГО, ЧТО ВСПОМНИЛИ.
 *
 * ⚠️ ЭТО ЕДИНСТВЕННОЕ, ЧТО ДЕЛАЕТ СЛОВО «КО ВСЕМУ» ПРОВЕРЯЕМЫМ. Метка,
 * которую надо не забыть поставить на новом экране, однажды не ставится — и
 * это ничем себя не проявит: картинка отрисуется, тесты пройдут, экран будет
 * выглядеть готовым. Ровно так в этом проекте разъезжались список Edge-функций
 * с папкой и число тестов с числом файлов.
 *
 * Поэтому здесь не проверяется «функция работает». Здесь обходится ВЕСЬ `src`
 * и требуется, чтобы каждый <img>, показывающий чужой файл, нёс метку
 * источника — сам или через компонент, который её ставит.
 *
 * ⚠️ ДЕКОРАТИВНЫЕ КОПИИ ИСКЛЮЧЕНЫ НАМЕРЕННО. В досье под снимком лежит его же
 * размытая копия (`aria-hidden`, `alt=""`) — тот же самый файл, уже
 * помеченный соседним элементом. Вторая метка на нём ничего не добавила бы,
 * а читалась бы как два разных изображения.
 */

/** Поля, в которых у нас лежат ссылки на ЧУЖИЕ файлы. */
const SCRAPED = /\b(photo_url|crest_url|image_url)\b/;

/** Компоненты, которые ставят метку внутри себя. */
const MARKS_ITSELF = [
  'src/shared/ui/PlayerPhoto.tsx',
  'src/features/fixtures/Crest.tsx',
];

function tsxFiles(dir: string): string[] {
  const out: string[] = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...tsxFiles(p));
    else if (e.name.endsWith('.tsx') && !e.name.endsWith('.test.tsx')) out.push(p);
  }
  return out;
}

/**
 * Каждый <img …/> файла целиком, вместе с атрибутами.
 *
 * ⚠️ ДВЕ ПОПРАВКИ, И ОБЕ ПО СЛЕДАМ СОБСТВЕННОГО ВРАНЬЯ ЭТОЙ ПРОВЕРКИ.
 *
 * Первая: границей служит `/>`, а не первый `>`. Резка по `>` обрывала тег на
 * стрелке внутри `onError={(e) => …}`, то есть не видела атрибутов, стоявших
 * дальше, и называла помеченные картинки голыми. В JSX <img> обязан быть
 * самозакрывающимся, поэтому `/>` — надёжная граница.
 *
 * Вторая: комментарии вырезаются ДО разбора. В шапке `PlayerPhoto` написано
 * «каждый экран писал свой `<img className="...">`» — и поиск цеплялся за
 * этот текст, дотягиваясь до настоящего тега далеко ниже. Проверка проходила,
 * но смотрела на склейку из комментария и кода: снимешь метку — краснеет не
 * тот файл и не по той причине.
 */
function imgTags(src: string): string[] {
  const code = src
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/^\s*\/\/.*$/gm, ' ');
  return [...code.matchAll(/<img\b[\s\S]*?\/>/g)].map((m) => m[0]);
}

describe('невидимая маркировка собранного контента', () => {
  const files = tsxFiles('src');

  it('находит экраны с картинками — иначе проверка пустая', () => {
    // ⚠️ ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ОБХОДА. Ошибись путь или расширение, и цикл
    // ниже прошёл бы по пустому списку, ничего не проверив и ни разу не
    // покраснев. Зелёная пустая проверка хуже красной.
    expect(files.length).toBeGreaterThan(50);
    const withImg = files.filter((f) => imgTags(readFileSync(f, 'utf8')).length > 0);
    expect(withImg.length).toBeGreaterThan(3);
  });

  it('каждый <img> с чужим файлом несёт метку источника', () => {
    const naked: string[] = [];
    for (const f of files) {
      const src = readFileSync(f, 'utf8');
      for (const tag of imgTags(src)) {
        if (!SCRAPED.test(tag)) continue;
        if (/aria-hidden=["{]?true/.test(tag)) continue;   // декоративная копия
        if (tag.includes('provenanceAttrs')) continue;
        naked.push(`${f}: ${tag.replace(/\s+/g, ' ').slice(0, 90)}`);
      }
    }
    expect(naked, 'чужой файл показывается без метки источника').toEqual([]);
  });

  it('общие компоненты ставят метку НА САМ <img>, а не просто импортируют её', () => {
    // ⚠️ И ЭТО ПОПРАВКА ПО СЛЕДАМ ПУСТОЙ ПРОВЕРКИ. Сначала здесь стояло
    // `toContain('provenanceAttrs')` по всему файлу — и оно проходило на
    // компоненте, у которого метку с тега сняли: строка-то оставалась в
    // строке импорта. Проверка зеленела ровно на той поломке, ради которой
    // написана.
    //
    // У этих двоих метка стоит один раз и работает на всех экранах сразу:
    // `photo_url` и `crest_url` тут не упоминаются (ссылка приходит пропсом),
    // поэтому обход выше их не видит, и стеречь их надо отдельно.
    for (const path of MARKS_ITSELF) {
      const tags = imgTags(readFileSync(path, 'utf8'));
      expect(tags.length, `${path}: <img> не найден — тест надо переписать`).toBe(1);
      expect(tags[0], `${path} перестал помечать источник`).toContain('provenanceAttrs');
    }
  });

  it('страница объявляет права машиночитаемо', () => {
    const html = readFileSync('index.html', 'utf8');
    expect(html).toMatch(/<link\s+rel="license"/);
    expect(html).toMatch(/name="rights"/);
  });
});
